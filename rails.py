_CLIP_BODY_RE = re.compile(r"def _clip_host_text\(.*?(?=\n(?:async )?def )", re.S)
_DEF_LINE_RE = re.compile(r"(?m)^(?:async )?def (\w+)\(")


def _clip_host_call_sites(src: str) -> list[str]:
    """Функции agent.py, где вывод хоста реально режется (кроме самого определения)."""
    out: list[str] = []
    for match in re.finditer(r"_clip_host_text\(", src):
        head = src[: match.start()]
        if head.endswith("def "):
            continue          # это само объявление, а не место реза
        names = _DEF_LINE_RE.findall(head)
        name = names[-1] if names else "?"
        if name == "_clip_host_text":
            continue
        name = name[5:] if name.startswith("tool_") else name
        if name not in out:
            out.append(name)
    return out


