# в педантизме: пока писался этот рельс, механику переписывал сосед — и запись, обещающая
# «письмо уходит только по заказу» до того, как заказ появился в коде, была бы ровно той
# ложью, ради снятия которой рельс и заводится. Каждая половина спрашивает у кода, что
# сейчас правда, и обе ветки ответа написаны.
_FOLLOWUPS = "telegram_followups.py"
_FOLLOWUP_LOOSE_RE = re.compile(r"explicit_only\s*=\s*False")
_FOLLOWUP_ACTIONS_RE = re.compile(r'return "action должен быть ([^"]+)\."')


def _code_only(text: str) -> str:
    """Исходник без строчных комментариев.

    Разница та же, что в сверке имён рычагов: `#` — записка тому, кто правит файл, и в ней
    цитата снятой строки («здесь стояло explicit_only=False») уместна и полезна. Если читать
    её как живой код, рельс объявит ей автоматизм, которого уже нет, — то есть соврёт ровно
    в момент починки. Наличие механики спрашиваем только у кода.
    """
    return re.sub(r"(?m)#.*$", "", text or "")


def _followup_ttl() -> tuple[float | None, str]:
    """(срок жизни следа, имя рычага). Имя рычага тоже читается: вписанное руками имя
    переживает переименование соседа молча — на этом уже обжигались дважды за день."""
    src = _code_only(_source_text(_FOLLOWUPS))
    # Не первое попавшееся имя: в этом файле уже есть PRAXIS_BASE, и он не имеет к сроку
    # никакого отношения — берём то, что действительно похоже на срок.
    env = next((n for n in re.findall(r"\bPRAXIS_[A-Z0-9_]+\b", src) if "TTL" in n), "")
    live = _live("telegram_followups", "TRACE_TTL_SEC")
    if isinstance(live, (int, float)) and not isinstance(live, bool):
        return float(live), env
    number = (_num_in(src, r"(?m)^TRACE_TTL_SEC = ([\d.]+)")
              or _num_in(src, r"def _trace_ttl\(\)[\s\S]*?return ([\d.]+)"))
    return number, env


def _num_in(text: str, pattern: str) -> float | None:
    """Число из уже прочитанного текста. Отдельно от `_from_source`, потому что здесь
    читается ОЧИЩЕННЫЙ от комментариев исходник: закомментированный старый кап не должен
    выдаваться за живой."""
    match = re.search(pattern, text)
    if not match:
        return None
    try:
        return float(match.group(1))
    except (TypeError, ValueError):
        return None


