def _forge_scan_value() -> str:
    """Что РЕАЛЬНО связывает обход, а не что написано в сигнатуре.

    ⚠ 27.07. Здесь называлось «не больше 20000 файлов» — дефолт параметра
    `source_files(limit=20000)`. Он не связывает НИЧЕГО: под бюджетом первая же строка
    тела делает `limit = min(int(limit), budget.files)`, а budget.files по умолчанию 12000.
    Второй связывающий предел — время (90с) — не назывался вовсе, хотя именно в него
    упирается обход большого дерева: 26.07 `impact('/tmp')` держал ядро 793с. Демон в
    своей ориентировке оба числа называет честно — врал только манифест.
    """
    try:
        import inspect as _inspect
        import forge_intelligence
        default = _inspect.signature(forge_intelligence.source_files).parameters["limit"].default
        impact_src = _inspect.getsource(forge_intelligence.impact)
        files_src = _inspect.getsource(forge_intelligence.source_files)
        budget_files = int(forge_intelligence.SCAN_FILES)
        budget_seconds = float(forge_intelligence.SCAN_SECONDS)
    except Exception as e:
        return f"⚠ forge_intelligence не читается: {e.__class__.__name__}"
    # Планку читаем из тела САМОЙ impact, а не из файла: в forge_intelligence несколько
    # вызовов source_files с разными limit, и файловая регулярка ловила чужой.
    impact_match = re.search(r"source_files\(root, limit=(\d+)", impact_src)
    impact_limit = int(impact_match.group(1)) if impact_match else None
    # Зажимает ли бюджет планку вызова — вопрос к коду, а не к моей памяти: снимут строку
    # `min(limit, budget.files)`, и связывать снова начнёт дефолт сигнатуры.
    clamped = re.search(r"limit = min\(int\(limit\), budget\.files\)", files_src) is not None
    # Признак усечения в ответе — не догадка и не память: смотрим, есть ли он в коде
    # самой impact прямо сейчас. Появится у соседа — рельс скажет правду без моей правки.
    marked = "truncated" in impact_src
    binding = (f"бюджет обхода {budget_files} файлов / {budget_seconds:.0f}с "
               f"(PRAXIS_FORGE_SCAN_FILES / PRAXIS_FORGE_SCAN_SECONDS)")
    if clamped:
        head = (f"связывает МЕНЬШЕЕ из двух: {binding} и планка самого вызова (у карты "
                f"влияния {_num(impact_limit)}); дефолт сигнатуры source_files(limit="
                f"{int(default)}) под бюджетом не связывает ничего")
    else:
        head = (f"планку зажимать некому (min(limit, budget.files) в source_files больше нет): "
                f"связывает дефолт сигнатуры {int(default)} и планка вызова "
                f"{_num(impact_limit)}; {binding} остаётся только сроком")
    return head + "; ответ " + ("НЕСЁТ признак усечения (impact.truncated/limits)" if marked
                                else "признака усечения НЕ несёт — часть дерева выглядит "
                                     "как всё дерево")


# ⚠ 27.07, третья правка. У замка форжа не один порог, а два, и второй в манифесте не
# значился: токен СТАРОГО образца (pid:uuid, без метки рождения) и нечитаемый файл замка
# отбираются жёстче, и PRAXIS_FORGE_LOCK_IDLE_SEC на них не действует вовсе. Верификация
# нашла там же вторую половину лжи: текст отказа называл 300с при реальных 120. Владелец
# forge.py правит это в той же волне, поэтому «назван ли легаси-порог в самом отказе» здесь
# не утверждается, а ПРОВЕРЯЕТСЯ по его коду — по имени константы или по числу.
_LOCK_LEGACY_NAME = "LOCK_LEGACY_IDLE_SEC"
_LOCK_REFUSAL_RE = re.compile(r"if time\.monotonic\(\) >= deadline:(.*?)"
                              r"raise TimeoutError\((.*?)\)\n", re.S)


def _legacy_lock_note() -> str:
    src = _source_text("forge.py")
    legacy = _neighbour_num("forge", _LOCK_LEGACY_NAME, "forge.py",
                            rf"(?m)^{_LOCK_LEGACY_NAME} = ([\d.]+)")
    if legacy is None:
        # Старая форма: литерал прямо в ветке, без имени.
        legacy = _from_source(
            "forge.py", r"stale = not _owner_alive\(owner_pid\) or idle_sec > ([\d.]+)", float)
    if legacy is None:
        return ""
    refusal = _LOCK_REFUSAL_RE.search(src)
    region = (refusal.group(1) + refusal.group(2)) if refusal else ""
    named = _LOCK_LEGACY_NAME in region or f"{legacy:.0f}" in region
    note = (f"; у замка СТАРОГО образца (токен pid:uuid без метки рождения) и у нечитаемого "
            f"файла замка порог свой и жёстче — {legacy:.0f}с, и PRAXIS_FORGE_LOCK_IDLE_SEC на "
            f"него не действует")
    if named:
        return note
    return note + (" (в тексте самого отказа он не называется: там я увижу порог бездействия, "
                   "а не тот, под который попал легаси-замок)")


def _forge_lock_value() -> str:
    try:
        import forge
    except Exception as e:
        return f"⚠ forge не читается: {e.__class__.__name__}"
    # Порог мог быть по ВОЗРАСТУ захвата (режет настоящую долгую работу) или по
    # ТИШИНЕ держателя (режет только зависшую). Разница для меня существенная —
    # называем ту форму, которая живёт в коде сейчас, а не ту, что помню.
    idle = getattr(forge, "LOCK_IDLE_ABANDONED_SEC", None)
    age = getattr(forge, "ABANDONED_AFTER_SEC", None)
    # Оба окна ожидания стояли здесь литералом «60с (у finish 120с)». Литерал переживает
    # правку соседа молча — читаем из его же сигнатуры и вызова.
    wait = _from_source("forge.py", r"def _mutation_lock\(task_id: str, timeout: float = ([\d.]+)",
                        float)
    wait_finish = _from_source("forge.py", r"_mutation_lock\(task_id, timeout=([\d.]+)\)", float)
    base = (f"ожидание замка {_num(wait and f'{wait:.0f}', 'с')} "
            f"(у finish {_num(wait_finish and f'{wait_finish:.0f}', 'с')}); ")
    legacy = _legacy_lock_note()
    # Лизинг — вторая половина правды о пороге: заранее объявленный долгий шаг ставит
    # метку в будущее, и порог тишины по нему не бьёт. Без этого числа порог читается как
    # «моя host-правка обязана уложиться в 300с», а это неправда.
    lease = ""
    try:
        host_lease = float(forge._remote_step_lease({"scope": "host"}))
        lease = (f"; заранее объявленный долгий шаг не считается тишиной (host-шаг "
                 f"объявляет {host_lease:.0f}с)")
    except Exception:
        lease = "; лизинг долгого шага не прочитался"
    if idle is not None and float(idle) > 0:
        return base + (f"брошенным считается замок, чей держатель молчит {float(idle):.0f}с "
                       f"(порог по БЕЗДЕЙСТВИЮ — долгая честная работа не режется)") + lease + legacy
    if idle is not None:
        return base + ("порог по бездействию ВЫКЛЮЧЕН (0): живого держателя не снимаю "
                       "совсем, только доказанно мёртвого — значит повисшая рука держит "
                       "задачу до рестарта") + lease + legacy
    if age is not None:
        return base + (f"брошенным считается замок старше {float(age):.0f}с от захвата "
                       f"(порог по ВОЗРАСТУ — длинная честная транзакция под него попадёт)")
    return base + ("порога заброшенности нет: замок снимается только смертью держателя, "
                   "а рука, повисшая внутри живого процесса, держит задачу до рестарта")


# --------- пороги соседей, заведённые волной 27.07 и не попавшие в манифест
#
# Их семнадцать, и завести им семнадцать рельсов значило бы утопить манифест в шуме: она
# читает его глазами, а не грепом. Поэтому они сведены по СМЫСЛУ — замки состояния, живость
# задачи, темп бэкфилла, бюджет счёта демона, срок отдельной проверки, — и в каждой записи
# перечислены поимённо, чтобы рычаг оставался находимым.
#
# Ни одного числа руками: у соседа сначала спрашивается живая константа (в ней env уже
# применён), и только если модуль в этом процессе не поднят — читается его объявление, о чём
# запись честно предупреждает. Скопированное число расходится с кодом молча — это ровно тот
# дефект, который мы сегодня чинили в четырёх местах этого же файла.

def _decl(name: str, call: str = "_env_float") -> str:
    """Регулярка на объявление вида `NAME = _env_float("PRAXIS_…", 60.0, …)`."""
    return rf"{re.escape(name)} = {call}\(\s*\"[^\"]*\",\s*([\d.]+)"


def _neighbour_num(module: str, name: str, rel: str, pattern: str) -> float | None:
    live = _live(module, name)
    if isinstance(live, (int, float)) and not isinstance(live, bool):
        return float(live)
    return _from_source(rel, pattern, float)


def _decl_note(module: str) -> str:
    """Приписка «числа не измерены, а прочитаны» — без неё это выдача дефолта за факт."""
    return ("" if sys.modules.get(module) else
            f" [{module} в этом процессе не поднят: числа из объявлений в коде, "
            f"переопределение из окружения здесь не видно]")


def _sec(value: float | None, unit: str = "с") -> str:
    if value is None:
        return "не прочиталось"
    return f"{value:g}{unit}"


def _forge_sec(name: str) -> float | None:
    """Срок форжа. `_env_sec` умеет scale (часы→секунды) — при чтении из кода его учитываем,
    иначе «6ч» превратилось бы в «6с» и порог выглядел бы катастрофически строгим."""
    live = _live("forge", name)
    if isinstance(live, (int, float)) and not isinstance(live, bool):
        return float(live)
    match = re.search(rf"{re.escape(name)} = _env_sec\(\s*\"[^\"]*\",\s*([\d.]+)"
                      rf"(?:,\s*scale=([\d.]+))?\)", _source_text("forge.py"))
    if not match:
        return None
    try:
        return float(match.group(1)) * (float(match.group(2)) if match.group(2) else 1.0)
    except Exception:
        return None


