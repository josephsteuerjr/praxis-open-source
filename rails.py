def _env(name: str, default: str) -> str:
    return os.getenv(name, default) or default


def _flag_on(name: str, default_on: bool = True) -> bool:
    raw = (os.getenv(name) or "").strip().lower()
    if not raw:
        return default_on
    return raw not in ("0", "false", "no", "off")


def _live(module: str, name: str):
    """Константа из УЖЕ поднятого модуля, иначе None.

    Сами не импортируем: registry() зовут и из её ответа, и из тестов, а `import agent`
    тянет весь мир и замыкает цикл agent → rails. Если модуля в процессе нет — рельс
    честно скажет, что показывает документированный дефолт, а не измеренное значение.
    """
    mod = sys.modules.get(module)
    if mod is None:
        return None
    try:
        return getattr(mod, name)
    except Exception:
        return None


