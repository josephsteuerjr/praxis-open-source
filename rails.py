def render_md() -> str:
    """soul/rails.md моими словами. Генерится кодом — правки руками перезапишутся."""
    rows = registry()
    counts: dict[str, int] = {}
    for r in rows:
        counts[r["cls"]] = counts.get(r["cls"], 0) + 1
    lines = [
        "# Мои рельсы — что меня держит и почему",
        "",
        "_Генерится кодом (rails.py) из фактических констант — не редактировать руками._",
        "_Классы: 🏠 дом (существование/секреты/третьи лица) · 🔓 решение Егора (его рычаг,",
        "помечено как его) · 🎒 моя дисциплина (соблюдаю/оспариваю/переписываю) · ⚙ физика среды._",
        "_«Так получилось в коде, и никто не знает» — пятый класс, то есть баг: тест ловит._",
        "",
        "Сводка: " + " · ".join(f"{_CLS_MARK[c]} {c}: {n}" for c, n in counts.items()),
        "",
    ]
    for r in rows:
        mark = _CLS_MARK.get(r["cls"], "•")
        lines.append(f"## {mark} {r['id']}")
        lines.append(f"- держит: {r['holds']}")
        lines.append(f"- класс: {r['cls']}; рычаг: {r['lever']}")
        lines.append(f"- сейчас: {r['value']}")
        lines.append(f"- почему: {r['why']}")
        lines.append("")
    return "\n".join(lines)


# Маркер класса необязателен: `(?:\S+\s+)?`, а не `\S*` — жадная звёздочка на заголовке
# БЕЗ маркера («## rail_x») откусывала бы имя и отдавала хвост («x») за id.
_HEADING_RE = re.compile(r"^##\s+(?:\S+\s+)?([A-Za-z0-9_]+)\s*$", re.M)


def manifest_ids(text: str) -> set[str]:
    """id рельсов из `## `-заголовков манифеста (маркер класса перед id не мешает)."""
    return {m.group(1) for m in _HEADING_RE.finditer(text or "")}


def manifest_drift() -> dict:
    """Отстал ли файл манифеста от кода. Дёшево: значения рельсов НЕ читаются.

    Нужна потому, что soul/rails.md пишет только сон (sleep.py), а сон отменяется по
    просьбе «останови фон» БЕЗ метки попытки — то есть манифест может замереть на
    произвольный срок и молча описывать вчерашний дом. Такое отставание она обязана
    видеть в той же строке, где видит счёт рельсов.

    -> {"missing": [...в коде есть, в файле нет...], "stale": [...в файле есть,
        в коде нет — это уже обещание несуществующего...], "ok": bool}
    """
    code = {r["id"] for r in registry(with_values=False)}
    try:
        on_disk = manifest_ids(RAILS_MD.read_text(encoding="utf-8"))
    except OSError:
        return {"missing": sorted(code), "stale": [], "ok": False, "file": False}
    return {"missing": sorted(code - on_disk), "stale": sorted(on_disk - code),
            "ok": code == on_disk, "file": True}


def sync_md() -> bool:
    """Записать манифест, только если изменился. True = переписала."""
    try:
        text = render_md()
        try:
            if RAILS_MD.read_text(encoding="utf-8") == text:
                return False
        except OSError:
            pass
        RAILS_MD.parent.mkdir(parents=True, exist_ok=True)
        tmp = RAILS_MD.with_suffix(".md.tmp")
        tmp.write_text(text, encoding="utf-8")
        tmp.replace(RAILS_MD)
        return True
    except Exception:
        log.warning("rails.sync_md не смог записать манифест", exc_info=True)
        return False


