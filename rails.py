    # сигнатуры context() — связывает тот, который есть, поэтому спрашиваем оба.
    lenta = (_neighbour_num("telegram_followups", "CONTEXT_LIMIT", _FOLLOWUPS,
                            r"(?m)^CONTEXT_LIMIT = (\d+)")
             or _num_in(src, r"def context\(self, \*, limit: int = (\d+)\)"))
