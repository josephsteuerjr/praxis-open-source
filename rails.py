_SERVERD_NON_WAIT_IDS = frozenset({"serverd.in_doubt_window"})


def _serverd_deadline_value() -> str:
    """Все сроки клиента демона — из `serverd_client.deadlines()`, не своим пересказом.

    ⚠ Первая редакция читала два getattr (DEFAULT/LONG) и называла ей два срока из пяти.
    Невидимыми оставались ровно те, что решают за неё: FAST 8с висит на `admin.status`,
    который зовётся при КАЖДОЙ сборке промпта и идёт ВНЕ потолка руки; SERVER_BUDGET —
    потолок бюджета демона на op.run, то есть усечение её же названного срока; окно
    повтора решает, пойдёт ли зависшая мутация под тем же номером или выполнится второй
    раз. Сосед специально опубликовал `deadlines()` — «чтобы манифест не выдумывал их
    заново»; выдумывать заново и значило врать на три срока из пяти.
    """
    try:
        import serverd_client
    except Exception as e:
        return f"⚠ serverd_client не читается: {e.__class__.__name__}"
    rows = None
    fn = getattr(serverd_client, "deadlines", None)
    if callable(fn):
        try:
            rows = list(fn())
        except Exception:
            rows = None      # константу снесли/переименовали — уходим на старый путь
    if rows:
        parts = []
        waits: list[float] = []
        for row in rows:
            rid = str(row.get("id") or "?")
            try:
                sec = float(row.get("seconds") or 0)
            except Exception:
                sec = 0.0
            if rid not in _SERVERD_NON_WAIT_IDS:
                waits.append(sec)
            tail = str(row.get("applies") or "").strip()
            env = str(row.get("env") or "").strip()
            parts.append(f"{rid} {sec:.0f}с" + (f" — {tail}" if tail else "")
                         + (f" [{env}]" if env else ""))
        ceiling = _live("agent", "TOOL_CEILING_SEC")
        if ceiling and float(ceiling) > 0 and waits:
            parts.append(f"потолок руки {float(ceiling):.0f}с — "
                         + ("вложенность в порядке" if max(waits) < float(ceiling)
                            else "⚠ срок НЕ меньше потолка: честный ответ демона до меня "
                                 "не дойдёт"))
        parts.append(_forge_remote_run_line())
        return "; ".join(p for p in parts if p)
    default = getattr(serverd_client, "DEFAULT_TIMEOUT_SEC", None)
    long_sec = getattr(serverd_client, "LONG_TIMEOUT_SEC", None)
    if default is None:
        return ("срока по глаголам НЕТ: любой вызов демона ждёт 3600с, а таймаут, "
                "принятый за обрыв транспорта, повторяется тем же rid — до 7200с молчания")
    parts = [f"обычный глагол {float(default):.0f}с"]
    if long_sec is not None:
        parts.append(f"длинный (host.*/inspect/audit) {float(long_sec):.0f}с")
    ceiling = _live("agent", "TOOL_CEILING_SEC")
    if ceiling and float(ceiling) > 0:
        worst = max(float(default), float(long_sec or 0))
        parts.append(f"потолок руки {float(ceiling):.0f}с — "
                     + ("вложенность в порядке" if worst < float(ceiling)
                        else "⚠ срок НЕ меньше потолка: честный ответ демона до меня не дойдёт"))
    parts.append("op.run — свой срок из аргумента")
    parts.append(_forge_remote_run_line())
    return "; ".join(p for p in parts if p)


def _forge_remote_run_line() -> str:
    """Шестой ярус той же матрёшки — и он не в serverd_client, а в forge.

    `deadlines()` его не публикует и опубликовать не может: это клампинг НАЗВАННОГО МНОЙ
    срока, который делает forge перед вызовом клиента. Молчать о нём — значит показывать
    пять ярусов из шести и оставлять необъяснимым, почему «без предела» превратилось
    в 540с.
    """
    limit = _forge_sec("REMOTE_RUN_DEADLINE_SEC")
    ceiling = _forge_sec("_HAND_CEILING_SEC")
    if limit is None:
        return ""
    if limit <= 0 or (ceiling is not None and ceiling <= 0):
        return ("forge.remote_run: свой предел снят (0 в PRAXIS_FORGE_REMOTE_RUN_SEC или в "
                "потолке руки) — названный мной срок не режется вовсе")
    hand = f" {ceiling:.0f}с" if ceiling is not None else ""
    return (f"forge.remote_run {limit:.0f}с [PRAXIS_FORGE_REMOTE_RUN_SEC] — столько получает "
            f"синхронная удалённая команда, когда я не назвала ДОСТИЖИМЫЙ срок (0 = «без "
            f"предела» или больше потолка руки{hand}); достижимый срок не трогается, "
            f"усечение называется в ответе")


# Двери наружу — все файлы, где живёт отправка. Судья приватности стоит ровно на одной из
# них, но манифест не имеет права утверждать это на память: 26.07 придержанный им материал
# ушёл через 48 секунд прямым тулом, и вся ценность этой записи в том, что она показывает
# контур СЕГОДНЯШНИМ. Поэтому считаем вызовы в исходнике, а не пересказываем прошлый разбор.
_JUDGE_NAME = "evaluate_reply"
_JUDGE_DOOR_FILES = ("agent.py", "mtproto_runner.py", "workshop.py", "core/narration.py")
# Точка вызова ловится и через атрибут: контур могут свести снаружи agent.py
# (`agent.evaluate_reply(...)` из раннера — ровно тот путь, которым идут прямые тулы).
# Присваивание (`agent.evaluate_reply = …`, так делают стенды) сюда не попадает: нужна «(».
_JUDGE_CALL_RE = re.compile(rf"(?<![\w.])(?:\w+\.)?{_JUDGE_NAME}\s*\(")
_JUDGE_DEF_RE = re.compile(rf"^\s*(?:async\s+)?def\s+{_JUDGE_NAME}\s*\(")
_ENCLOSING_DEF_RE = re.compile(r"^(\s*)(?:async\s+)?def\s+(\w+)\s*\(")


def _enclosing_def(lines: list[str], idx: int) -> str:
    """Имя функции, внутри которой стоит строка idx (1-based); '' — не нашлось.

    Ищем ближайшее объявление С МЕНЬШИМ отступом, а не первое сверху: вызов может стоять
    в методе класса, и «ближайший def в файле» назвал бы соседа этажом ниже.
    """
    line = lines[idx - 1]
    indent = len(line) - len(line.lstrip())
    for back in range(idx - 1, 0, -1):
        match = _ENCLOSING_DEF_RE.match(lines[back - 1])
        if match and len(match.group(1)) < indent:
            return match.group(2)
    return ""


def outbound_judge_sites() -> list[tuple[str, int, str]]:
    """[(файл, строка, объемлющая функция)] — где судью приватности ВПРАВДУ зовут.

    Комментарии снимаются перед счётом. Это не педантизм: в agent.py про
    `evaluate_reply(collect_state=True)` написано дважды в пояснительных записках, и
    наивный поиск насчитал бы три судимых пути там, где он ровно один. Ровно таким
    способом соседний рельс уже однажды нашёл кап судьи в комментарии и назвал ей
    несуществующее число.

    Пустой список означает ДВЕ разные вещи — «судью не зовёт никто» и «исходники не
    прочитались»; различает их вызывающий, а не эта функция.
    """
    sites: list[tuple[str, int, str]] = []
    for rel in _JUDGE_DOOR_FILES:
        lines = _code_only(_source_text(rel)).splitlines()
        for idx, line in enumerate(lines, 1):
            if _JUDGE_DEF_RE.match(line) or not _JUDGE_CALL_RE.search(line):
                continue
            sites.append((rel, idx, _enclosing_def(lines, idx)))
    return sites


