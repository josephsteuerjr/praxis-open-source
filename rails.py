# --------- пределы, которые живут литералом в чужом файле, а не импортируемой константой
#
# Соблазн был переписать эти числа сюда руками. Так делать нельзя: манифест, где число
# скопировано, врёт со следующей же правкой соседа — и врёт МОЛЧА, то есть ровно тем
# способом, против которого он написан. Поэтому читаем прямо из исходника, с кэшем по
# mtime; не прочиталось — так и говорим, а не подставляем «как было в прошлый раз».
#
# CODE_DIR — каталог кода (рядом с этим файлом), НЕ BASE: BASE тесты уводят во временную
# папку, а исходники всё это время лежат там же, где и мы.
CODE_DIR = Path(__file__).resolve().parent

_SRC_CACHE: dict[str, tuple[float, str]] = {}


def _source_text(rel: str) -> str:
    path = CODE_DIR / rel
    try:
        mtime = path.stat().st_mtime_ns
    except OSError:
        return ""
    hit = _SRC_CACHE.get(rel)
    if hit and hit[0] == mtime:
        return hit[1]
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""
    _SRC_CACHE[rel] = (mtime, text)
    return text


def _from_source(rel: str, pattern: str, cast=int):
    """Первая группа регулярки из исходника, или None. None = «не смогла прочесть»."""
    match = re.search(pattern, _source_text(rel))
    if not match:
        return None
    try:
        return cast(match.group(1))
    except Exception:
        return None


