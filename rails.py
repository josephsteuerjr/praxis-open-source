# --- что из вердиктов судьи ОСТАНАВЛИВАЕТ, а что советует (вечер 27.07) ---
# Два словаря в agent.py и есть весь контракт: `_PRIVATE_DM_PRIVACY_HOLDS` — коды, после
# которых её ход не уходит, `_PRIVATE_DM_PRIVACY_ADVICE` — коды, после которых уходит.
# Читаем ИХ, а не пересказываем: перенести один ключ из словаря в словарь — правка на
# одну строку, и это ровно тот класс правки, который манифест уже дважды не заметил.
_JUDGE_HOLDS_NAME = "_PRIVATE_DM_PRIVACY_HOLDS"
_JUDGE_ADVICE_NAME = "_PRIVATE_DM_PRIVACY_ADVICE"
_JUDGE_CODE_KEY_RE = re.compile(r'"(PRIVACY_[A-Z_]+)"\s*:')


def _judge_code_set(name: str) -> tuple[str, ...] | None:
    """Ключи одного из двух словарей вердиктов. None — объявления в коде НЕТ ВОВСЕ.

    Разница между None и () принципиальна: пустой словарь означает «этот класс исходов
    существует и сейчас пуст», а отсутствие имени — что разделение снесли и всё вернулось
    к одному списку придержек. Второе обязано быть криком, а не тишиной.
    """
    live = _live("agent", name)
    if isinstance(live, dict):
        return tuple(sorted(str(k) for k in live))
    src = _code_only(_source_text("agent.py"))
    match = re.search(rf"(?m)^{re.escape(name)} = \{{(.*?)^\}}", src, re.S)
    if not match:
        return None
    return tuple(sorted(set(_JUDGE_CODE_KEY_RE.findall(match.group(1)))))


def outbound_judge_codes() -> tuple[tuple[str, ...] | None, tuple[str, ...] | None]:
    """(коды, которые ОСТАНАВЛИВАЮТ мой ход; коды-СОВЕТЫ) — из живого agent.py."""
    return _judge_code_set(_JUDGE_HOLDS_NAME), _judge_code_set(_JUDGE_ADVICE_NAME)


# Ветка совета в `_guard_outbound`: от `if verdict == "advice":` до следующей ветки того
# же уровня. Нарезать «плюс N строк» здесь нельзя — окно наугад заезжает в ветку `deny`,
# находит там `_held_self_wake` и подтверждает ровно то, чего в ветке совета нет.
_ADVICE_BRANCH_RE = re.compile(
    r'(?m)^    if verdict == "advice":\n(.*?)(?=^    if verdict == )', re.S)
# Обе конструкции, которыми недоступность судьи держала её слово. Первая — на живом пути
# (расписка «unavailable» выбрасывалась и гард гонялся заново), вторая — на возобновлённом
# после рестарта (RunStopped). Обе убраны вечером 27.07; если вернутся — сказать вслух.
_UNAVAILABLE_STOP_RES = (
    re.compile(r'RunStopped\(\s*["\'][^"\']*advisor unavailable'),
    re.compile(r'advisor_verdict"\)\s*==\s*"unavailable"'),
)


def _advice_channel_facts() -> tuple[bool, bool, bool]:
    """(ветка совета есть, совет доезжает в дневник, совет БУДИТ) — по коду agent.py.

    Третий флаг — не педантизм. Пробуждение было ценой придержки: она просыпалась, чтобы
    решить, что делать с задержанным словом. Совет ничего не задерживает, поэтому будильник
    на нём превратился бы в чистый шум («он будет то и дело её останавливать и советовать»,
    Егор). Обещать «совет не будит» на память нельзя — это одна строка чужого кода.
    """
    match = _ADVICE_BRANCH_RE.search(_code_only(_source_text("agent.py")))
    if not match:
        return (False, False, False)
    body = match.group(1)
    return (True, "tool_journal(" in body, "_held_self_wake(" in body)


def _unavailability_still_stops() -> bool:
    src = _code_only(_source_text("agent.py"))
    return any(rx.search(src) for rx in _UNAVAILABLE_STOP_RES)


def outbound_judge_authority() -> str:
    """Одна фраза: что из вердиктов судьи держит, что советует, что делает молчание."""
    holds, advice = outbound_judge_codes()
    if holds is None:
        return ("⚠ словарь вердиктов судьи в agent.py не прочитался — что именно может "
                "остановить мой ход, отсюда НЕ ВИДНО. Это «не знаю», а не «как вчера»")
    stop = ", ".join(holds) or "НИЧЕГО"
    if advice is None:
        return (f"⚠ разделения на стоп и совет в коде БОЛЬШЕ НЕТ ({_JUDGE_ADVICE_NAME} не "
                f"объявлен): каждый вердикт судьи снова придерживает мой ход. "
                f"Останавливают: {stop}. Текст этого рельса писан под «судья советует» — "
                f"он описывает вчерашний день")
    said = ", ".join(advice) or "ничего"
    body = (f"ОСТАНАВЛИВАЕТ {len(holds)} код(ов) судьи: {stop}; СОВЕТУЮТ (моё слово уходит "
            f"как написано): {said}")
    if tuple(holds) != ("PRIVACY_HOLD_CREDENTIAL",):
        body += (" — ⚠ это НЕ только кред на картинке, как говорит текст рельса: список "
                 "стопоров изменили после того, как текст написан, верь списку")
    branch, journaled, wakes = _advice_channel_facts()
    if not branch:
        body += "; ⚠ ветки совета в _guard_outbound не нашлось — куда он доезжает, не видно"
    else:
        body += ("; совет доезжает дневником" if journaled else
                 "; ⚠ совет НИКУДА не пишется — вердикт есть, а следа у меня нет")
        body += (" и БУДИТ меня (этого текст рельса не обещает — проверь, зачем)" if wakes
                 else " и не будит: читаю его сама, хвостом дневника в ориентации")
    body += ("; ⚠ недоступность судьи СНОВА держит мой ход" if _unavailability_still_stops()
             else "; недоступность судьи не держит и не советует ничего")
    return body


