# Предел, который связывает, живёт литералом в СИГНАТУРЕ тула, а не в константе модуля.
# Такой не ловится ни поиском по PRAXIS_*, ни описью верхнего уровня — verification_deadline
# нашёлся случайно. У поднятого модуля спрашиваем живую сигнатуру (её можно подменить, и
# рельс обязан поехать за подменой), иначе читаем объявление.
def _tool_signature_default(module: str, func: str, param: str, rel: str) -> int | None:
    live = _live(module, func)
    if live is not None:
        try:
            import inspect as _inspect
            value = _inspect.signature(live).parameters[param].default
            if isinstance(value, (int, float)) and not isinstance(value, bool):
                return int(value)
        except Exception:
            pass
    return _from_source(rel, rf"def {re.escape(func)}\([^)]*?{re.escape(param)}: int = (\d+)")


