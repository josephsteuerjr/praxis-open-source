# Приписка вида `cap 4000 chars, cut on line boundaries` внутри блока, который читает
# судья. У блоков STATE и ориентации она есть (владелец agent.py дописал её вместе с
# расщеплением слота), у остальных пяти видов улик срез немой. Проверяем ПО КОДУ: список,
# набитый сюда руками, переживёт правку соседа и превратится в очередную цитату-призрак.
def _judge_cap_announced(const: str | None, value: int | None) -> bool:
    src = _code_only(_source_text("agent.py"))
    if const:
        return bool(re.search(rf"cap \{{{re.escape(const)}\}}", src))
    if value is None:
        return False
    return bool(re.search(rf"cap {value}\b", src))


