def _followup_tool_actions() -> list[str] | None:
    """Что по нитям принимает САМ тул telegram_account — то есть до чего дотягиваюсь я.

    Спрашивается именно тул, а не раннер: раннер — внутренняя кухня, и его список действий
    может уйти вперёд (27.07 так и было — `watch`/`unwatch` уже жили в раннере, когда в
    схеме тула их ещё не было). Назвать её рукой то, чего в схеме нет, значит выдать ей
    рычаг, который она нажмёт и не получит ничего.
    """
    live = _live("agent", "TELEGRAM_ACCOUNT_TOOL")
    names: list[str] = []
    if isinstance(live, dict):
        try:
            names = list(live["input_schema"]["properties"]["action"]["enum"])
        except Exception:
            names = []
    if not names:
        # Регулярка якорится на ИМЯ тула: в agent.py таких enum-блоков много, и первый
        # попавшийся принадлежит чужому инструменту — по нему рельс объявил бы, что рук
        # по нитям у меня нет вовсе.
        src = _code_only(_source_text("agent.py"))
        tool = re.search(r"TELEGRAM_ACCOUNT_TOOL = \{.*?\n\}", src, re.S)
        block = re.search(r'"action": \{"type": "string", "enum": \[(.*?)\]\}',
                          tool.group(0) if tool else "", re.S)
        if not block:
            return None
        names = re.findall(r'"([a-z_]+)"', block.group(1))
    return [n for n in names if "followup" in n or "watch" in n]


def _followup_hand(runner: str) -> str:
    mine = _followup_tool_actions()
    inner = _FOLLOWUP_ACTIONS_RE.search(runner)
    inner_actions = inner.group(1) if inner else ""
    if mine is None:
        return "какие действия по нитям принимает telegram_account, из кода не прочиталось"
    if not mine:
        hand = "⚠ по нитям тул не принимает ни одного действия — леджер живёт мимо моих рук"
    else:
        hand = "мои действия над нитью: " + ", ".join(mine)
        if not any("watch" in n for n in mine):
            hand += " — то есть погасить нить могу, а завести отчёт или снять его нет"
    if not any("watch" in n for n in mine) and "watch" in inner_actions:
        hand += ("; ⚠ раннер такую команду уже принимает (" + inner_actions.strip()
                 + "), но в схеме тула её нет — до меня рычаг ещё не доведён")
    return hand


