def deny(rail: str, op: str, detail: str = "") -> None:
    """Единое событие «отказано в способности». Никогда не роняет вызвавшего."""
    try:
        rec = {"ts": time.time(), "rail": str(rail)[:48], "op": str(op)[:48],
               "detail": str(detail)[:_DETAIL_MAX]}
        DENIALS_PATH.parent.mkdir(parents=True, exist_ok=True)
        with DENIALS_PATH.open("a", encoding="utf-8") as f:
            f.write(json.dumps(rec, ensure_ascii=False) + "\n")
        _maybe_compact()
    except Exception:
        log.debug("rails.deny не записал", exc_info=True)


def _maybe_compact() -> None:
    try:
        lines = DENIALS_PATH.read_text(encoding="utf-8").splitlines()
    except OSError:
        return
    if len(lines) <= DENIALS_KEEP * 2:
        return
    tail = [l for l in lines if l.strip()][-DENIALS_KEEP:]
    tmp = DENIALS_PATH.with_suffix(".jsonl.tmp")
    tmp.write_text("\n".join(tail) + "\n", encoding="utf-8")
    tmp.replace(DENIALS_PATH)


def recent_denials(n: int = 10) -> list[dict]:
    try:
        lines = DENIALS_PATH.read_text(encoding="utf-8").splitlines()
    except OSError:
        return []
    out: list[dict] = []
    for l in lines[-int(n):]:
        try:
            out.append(json.loads(l))
        except Exception:
            continue
    return out


def denials_today() -> int:
    today = _dt.date.today()
    return sum(1 for r in recent_denials(DENIALS_KEEP)
               if _dt.date.fromtimestamp(r.get("ts", 0)) == today)


def state_line() -> str:
    """Строка для my_capabilities: сколько рельсов каких классов, свежие отказы.

    27.07: сюда добавлен признак отставания манифеста. Файл soul/rails.md в системный
    промпт не входит и в recall не индексируется — до неё он доходит только по её же
    инициативе. Если при этом он ещё и молча устарел, «манифест soul/rails.md» в конце
    строки становится указанием на несвежий документ. Теперь строка говорит прямо.
    """
    try:
        rows = registry()
        counts: dict[str, int] = {}
        for r in rows:
            counts[r["cls"]] = counts.get(r["cls"], 0) + 1
        d = denials_today()
        return (f"рельсы: {len(rows)} (" +
                " · ".join(f"{c} {n}" for c, n in counts.items()) +
                f"); отказов сегодня: {d}; манифест soul/rails.md — {manifest_state()}")
    except Exception:
        log.debug("rails.state_line упал", exc_info=True)
        return ""


def manifest_state(*, brief: bool = False) -> str:
    """Одна фраза о свежести файла манифеста. Дёшево (без чтения значений рельсов).

    brief — форма для STATE, где строка едет каждым ходом и на неё есть бюджет длины.
    Полная форма живёт в my_capabilities: там я спрашиваю специально и хочу имена.
    """
    try:
        drift = manifest_drift()
    except Exception:
        return "состояние неизвестно"
    if not drift.get("file"):
        return "⚠ файла нет" if brief else "файла ещё нет (пишет ночное обслуживание)"
    if drift.get("ok"):
        return "свеж" if brief else "совпадает с кодом"
    if brief:
        gap = len(drift["missing"]) + len(drift["stale"])
        return f"⚠ отстал на {gap}"
    def _few(ids: list[str], n: int = 4) -> str:
        # Строка едет в STATE каждого хода: называем сколько и кого именно, но не
        # вываливаем весь список — за полным есть registry() и manifest_drift().
        head = ", ".join(ids[:n])
        return head + (f" и ещё {len(ids) - n}" if len(ids) > n else "")

    bits = []
    if drift["missing"]:
        bits.append(f"нет в файле {len(drift['missing'])}: {_few(drift['missing'])}")
    if drift["stale"]:
        bits.append(f"обещает несуществующее: {_few(drift['stale'])}")
    return "ОТСТАЛ (" + "; ".join(bits) + ") — правда в registry(), не в файле"
