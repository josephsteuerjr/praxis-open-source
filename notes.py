def local_now_from(ts: float) -> _dt.datetime:
    """Момент `ts` её часами. Тот же расчёт, что в _local_now, но для прошлого события."""
    tz_name = (os.getenv("PRAXIS_TZ") or "Europe/Moscow").strip()
    try:
        from zoneinfo import ZoneInfo

        return _dt.datetime.fromtimestamp(float(ts), ZoneInfo(tz_name))
    except Exception:
        try:
            off = int(os.getenv("PRAXIS_TZ_OFFSET_H", "3"))
        except ValueError:
            off = 3
        return _dt.datetime.fromtimestamp(float(ts), _dt.timezone(_dt.timedelta(hours=off)))


def _local_now() -> _dt.datetime:
    """Её часы, а не часы контейнера.

    Записка штамповалась `datetime.now()`, то есть UTC (в контейнере задан только
    PRAXIS_TZ, TZ нет), а её собственные часы во всех остальных местах кадра рисуются
    в PRAXIS_TZ. 01.08 это стоило повтора: утреннее приветствие, отправленное в 07:30
    по её времени, лежало в записке как «03:30» — в кадре, где «сейчас 09:29», оно
    читается как ночное сообщение, а не как «я уже сегодня здоровалась».

    Логика та же, что в heartbeat.local_now; импортировать heartbeat отсюда нельзя —
    записка обязана оставаться листом без зависимостей (её пишут два процесса).
    """
    tz_name = (os.getenv("PRAXIS_TZ") or "Europe/Moscow").strip()
    try:
        from zoneinfo import ZoneInfo

        return _dt.datetime.now(ZoneInfo(tz_name))
    except Exception:
        try:
            off = int(os.getenv("PRAXIS_TZ_OFFSET_H", "3"))
        except ValueError:
            off = 3
        return _dt.datetime.now(_dt.timezone(_dt.timedelta(hours=off)))


def path_for(chat_id: str | int) -> Path:
    return SCRATCH_DIR / f"{_safe(chat_id)}.md"


#: Голова записи — штамп из append(): f"{_local_now():%H:%M} · {line}". Строка без
#: головы — продолжение предыдущей записи, а не самостоятельная запись.
_ENTRY_HEAD = re.compile(r"^\d{1,2}:\d{2} · ")


def _entries(lines: list[str]) -> list[list[str]]:
    """Строки записки → ЗАПИСИ. Ведущая группа без головы — обломок, а не запись."""
    groups: list[list[str]] = []
    for line in lines:
        if _ENTRY_HEAD.match(line) or not groups:
            groups.append([line])
        else:
            groups[-1].append(line)
    return groups


def _tail(lines: list[str], keep: int) -> list[str]:
    """Последние `keep` записей ЦЕЛИКОМ.

    Безголовый ведущий кусок отбрасывается: он остался от прежнего схлопывания по
    строкам и читается как чужая фраза без времени и без начала. Но только когда есть
    что оставить взамен — записка без единого штампа (старый формат, ручная правка)
    отдаётся как есть, иначе починка съела бы её память целиком.
    """
    groups = _entries(lines)
    if len(groups) > 1 and not _ENTRY_HEAD.match(groups[0][0]):
        groups = groups[1:]
    return [line for group in groups[-keep:] for line in group]


def read(chat_id: str | int, max_entries: int = MAX_ENTRIES) -> str:
    """Её записка себе по этому разговору — ровно её собственная нить.

    ⚠ Здесь была склейка с соседними ветками одной комнаты, отсортированная по `ЧЧ:ММ`
    из самой строки. Даты в строке нет: позавчерашняя запись в 23:50 обгоняла сегодняшнюю
    в 09:10, а хвостовой срез `[-max_lines:]` выбрасывал именно сегодняшнюю. Её свежая
    записка исчезала целиком, а `said_recently` начинал отвечать «нет» на то, что она
    сказала минуту назад (адверсарка 25.07, три независимых воспроизведения).

    Ради чего склейка делалась — анти-повтор через ветки — живёт теперь в
    `said_recently`, где порядок строк вообще не нужен: там вопрос «говорила ли», а не
    «в каком порядке». Чинить порядок в том, чему порядок не нужен, было ошибкой.

    ⚠ 03.08.2026 вторая половина той же ошибки: срез брался по СТРОКАМ (`lines[-n:]`),
    а записи многострочные — 52% на её живых файлах. Поэтому окно регулярно
    приземлялось в середину записи, и она читала хвост чужой фразы без времени и без
    начала. Теперь единица среза — ЗАПИСЬ, и запись либо видна целиком, либо не видна.
    """
    p = path_for(chat_id)
    if not p.exists():
        return ""
    lines = [l for l in p.read_text(encoding="utf-8", errors="ignore").splitlines()
             if l.strip()]
    return "\n".join(_tail(lines, max_entries))


def _sibling_files(chat_id: str | int) -> list[Path]:
    """Записки соседних веток ОДНОГО места (для анти-повтора, не для показа)."""
    own = path_for(chat_id)
    out = [own]
    try:
        import telegram_routes
        room = telegram_routes.room_of(chat_id)
        if room and SCRATCH_DIR.exists():
            for other in sorted(SCRATCH_DIR.glob(f"{_safe(room)}*.md")):
                if other != own and telegram_routes.same_room(other.stem, chat_id):
                    out.append(other)
    except Exception:
        pass
    return out


def _acquire(fd: int, wait_sec: float) -> tuple[bool, str]:
    """Взять межпроцессный замок на открытом дескрипторе. Отдаёт (взяли, почему нет).

    Опрос неблокирующими попытками, а не блокирующий flock: так у ожидания есть срок.

    ⚠ Вторая половина ответа — не украшение. «Занято» и «том не умеет замки» — РАЗНЫЕ
    вещи, и путать их значит врать о месте, где она живёт: первое временно (кто-то пишет
    прямо сейчас и вот-вот отпустит), второе не пройдёт никогда, сколько ни жди, и лечится
    только переездом тома. Раньше обе ветки сливались в голое False, и `lock_kind()`
    объявлял занятый на полсекунды замок несуществующим механизмом.
    """
    if _fcntl is not None:
        def _try() -> None:
            _fcntl.flock(fd, _fcntl.LOCK_EX | _fcntl.LOCK_NB)
    elif _msvcrt is not None:
        def _try() -> None:
            os.lseek(fd, 0, os.SEEK_SET)
            _msvcrt.locking(fd, _msvcrt.LK_NBLCK, 1)
    else:                                          # pragma: no cover — ни того, ни другого
        return False, "none: в этом питоне нет ни fcntl, ни msvcrt"
    busy = {errno.EACCES, errno.EAGAIN, errno.EWOULDBLOCK, errno.EDEADLK}
    wait_sec = max(0.0, wait_sec)
    deadline = time.monotonic() + wait_sec
    delay = 0.001
    while True:
        try:
            _try()
            return True, ""
        except OSError as exc:
            if exc.errno not in busy:              # EOPNOTSUPP, ENOLCK, EINVAL и прочее
                name = errno.errorcode.get(exc.errno, "?")
                return False, f"none: том не умеет замки ({name} {exc.errno})"
            if time.monotonic() >= deadline:
                return False, f"busy: занят другим писателем, ждала {wait_sec:g}с"
            time.sleep(delay)
            delay = min(delay * 2, 0.05)


def _same_file(fd: int, path: Path) -> bool:
    """Тот ли файл лежит сейчас по этому пути, что мы держим открытым.

    ⚠ Замок ядра живёт на INODE, а не на имени. Удалить `.lock` (руками, чисткой мусора,
    чем угодно) — и держатель останется сторожить покойника, а следующий писатель создаст
    файл с тем же именем и возьмёт на нём «свободный» замок: взаимное исключение исчезает
    МОЛЧА, и оба идут схлопывать записку каждый по своему снимку. Воспроизведено 27.07.
    Здесь мы это как минимум замечаем — и говорим вслух (см. append).

    На томах, где inode не настоящий (нули), не судим вовсе: лучше не знать, чем кричать
    впустую.
    """
    try:
        mine, there = os.fstat(fd), os.stat(str(path))
    except OSError:
        return False
    if not mine.st_ino or not there.st_ino:        # pragma: no cover — экзотические тома
        return True
    return (mine.st_ino, mine.st_dev) == (there.st_ino, there.st_dev)


class _Held:
    """Что вышло из попытки взять межпроцессный замок: взяли ли, почему нет, цел ли он ещё."""

    __slots__ = ("owned", "why", "_fd", "_path")

    def __init__(self, owned: bool, why: str, fd: int | None, path: Path | None):
        self.owned = owned
        self.why = why
        self._fd = fd
        self._path = path

    def intact(self) -> bool:
        """Всё ещё ли наш замок сторожит ЖИВОЙ `.lock`, а не удалённый inode."""
        if not self.owned or self._fd is None or self._path is None:
            return False
        return _same_file(self._fd, self._path)


def _release(fd: int) -> None:
    if _fcntl is not None:
        _fcntl.flock(fd, _fcntl.LOCK_UN)
    elif _msvcrt is not None:                      # pragma: no cover — ветка Windows
        os.lseek(fd, 0, os.SEEK_SET)
        _msvcrt.locking(fd, _msvcrt.LK_UNLCK, 1)


@contextlib.contextmanager
def _exclusive(p: Path):
    """Межпроцессный замок на СОСЕДНЕМ файле `.<имя>.lock`, а не на самой записке.

    Замок нужен именно на отдельном inode: записку схлопывают через `os.replace`, то есть
    её inode меняется, и замок, взятый на ней самой, после подмены сторожил бы уже
    удалённый файл — а следующий писатель взял бы «свободный» замок на новом.

    Замок ядра, а не файл-маркер: он снимается сам при закрытии дескриптора и при смерти
    процесса. Покойник его не уносит — в отличие от `.mutation.lock` в forge.py, где эту
    цену уже платили дважды. Поэтому здесь не нужны ни метка рождения, ни порог заброшенности.

    ⚠ Сайдкары `.lock` НЕ убираются, и это решение, а не забывчивость: удаление `.lock` —
    ровно тот способ молча снять взаимное исключение, который описан в `_same_file`. Цена
    известна и мала: по одному ПУСТОМУ файлу на записку, которую хоть раз писали после
    выката замка. Замерено на проде 27.07: 129 записок, 12 сайдкаров, весь каталог 528 КБ —
    сайдкар появляется лениво и в пределе даёт один нулевой inode на записку, то есть
    сотни пустых файлов, а не мегабайты. Цена уборки — потерянная строка её речи.

    Отдаёт `_Held`, а не бросает: не взяли — запись всё равно состоится (см. append).
    """
    global _DEGRADED_UNTIL
    lock_path = p.with_name("." + p.name + ".lock")
    degraded = time.monotonic() < _DEGRADED_UNTIL
    wait = _LOCK_WAIT_DEGRADED_SEC if degraded else _LOCK_WAIT_SEC
    fd = None
    owned = False
    why = ""
    for _attempt in range(2):                      # одна переоткрытая попытка на разовую чистку
        try:
            fd = os.open(str(lock_path), os.O_RDWR | os.O_CREAT, 0o600)
        except OSError as exc:
            fd, owned = None, False
            why = f"none: файл замка не открылся ({exc.errno})"
            break
        owned, why = _acquire(fd, wait)
        if owned and not _same_file(fd, lock_path):
            # Пока мы брали замок, `.lock` подменили — наш держится за удалённый inode,
            # то есть не держит ничего. Отпускаем и пробуем ещё раз с новым файлом.
            with contextlib.suppress(OSError):
                _release(fd)
            with contextlib.suppress(OSError):
                os.close(fd)
            fd, owned = None, False
            why = "none: файл замка подменяют под нами — взаимного исключения нет"
            continue
        break
    if owned:
        _DEGRADED_UNTIL = 0.0                      # замки живы — короткий режим не нужен
    elif why.startswith("busy:") and not degraded:
        _DEGRADED_UNTIL = time.monotonic() + _LOCK_DEGRADE_FOR_SEC
        # Число записок считаем ЖИВЬЁМ, а не подставляем замеренное когда-то: оно растёт
        # (122 → 129 за один день 27.07), а это строка, которую она читает про свой дом.
        # Считать здесь дёшево: ветка срабатывает не чаще раза в _LOCK_DEGRADE_FOR_SEC на
        # процесс и уже после того, как мы прождали целых _LOCK_WAIT_SEC.
        try:                       # свою записку считаем тоже: файл может ещё не родиться,
            names = {q.name for q in SCRATCH_DIR.glob("*.md")}   # _append_raw идёт ниже
            names.add(p.name)
            count = f"{len(names)} записок"
        except OSError:
            count = "сколько их сейчас — не сосчиталось"
        # Никакого «сложилось бы в минуты»: при малом числе записок это было бы неправдой,
        # а число тут живое и может быть любым. Говорим ровно факт — сколько их и что
        # ожидание платится за каждую; вывод пусть делает читатель.
        log.warning("записка [%s]: %s — следующие %g с в этом процессе жду замок %g с "
                    "вместо %g с: записок сейчас %s, и полное ожидание платится за "
                    "каждую отдельно; строки при этом ложатся, отменяется только "
                    "схлопывание файла по длине",
                    p.name, why, _LOCK_DEGRADE_FOR_SEC, _LOCK_WAIT_DEGRADED_SEC,
                    _LOCK_WAIT_SEC, count)
    try:
        yield _Held(owned, why, fd, lock_path)
    finally:
        if fd is not None:
            try:
                if owned:
                    _release(fd)
            except OSError:
                pass
            try:
                os.close(fd)
            except OSError:
                pass


def lock_kind() -> str:
    """Каким механизмом межпроцессный замок берётся ЗДЕСЬ — и берётся ли вообще.

    Живая проба, а не декларация: `fcntl.flock` на bind-маунте `/app/memory` никем не был
    проверен, пока 27.07 не проверили на проде (восемь процессов сериализовались, 8 строк
    из 8 дожили). Готовая однострочная проверка после деплоя.

    Три РАЗНЫХ ответа, и разница для неё существенная:
      • `flock` / `msvcrt` — механизм есть и сейчас свободен;
      • `busy: …` — механизм ЕСТЬ, но прямо сейчас его держит другой писатель. Временно,
        пройдёт само;
      • `none: …` — этого том (или питон) не умеет. Свойство МЕСТА, где она живёт: само
        не пройдёт, межпроцессной половины защиты здесь не будет никогда, и схлопывание
        идёт по потолку `MAX_ENTRIES * _UNLOCKED_TRIM_FACTOR` (он в СТРОКАХ: это
        про размер файла, а не про читаемость).
    ⚠ Раньше вторые два ответа сливались в одно «none: замок не берётся на этом томе» —
    занятый на полсекунды замок читался как «том не умеет». Одно лечится ожиданием,
    другое переездом; выдавать первое за второе — врать ей о её же доме.

    Проба идёт на ОБЩЕМ файле `.lockprobe`, своего на процесс нарочно не заводим: иначе
    диагностика плодила бы мусор и никогда не показывала бы «занято».
    """
    try:
        SCRATCH_DIR.mkdir(parents=True, exist_ok=True)
        fd = os.open(str(SCRATCH_DIR / ".lockprobe"), os.O_RDWR | os.O_CREAT, 0o600)
    except OSError as exc:
        return f"none: {exc.__class__.__name__} {exc.errno}"
    try:
        ok, why = _acquire(fd, _PROBE_WAIT_SEC)
        if not ok:
            return why or "none: замок не взялся и не сказал почему"
        try:
            _release(fd)
        except OSError as exc:
            return f"none: замок не отпускается ({exc.errno})"
    finally:
        try:
            os.close(fd)
        except OSError:
            pass
    return "flock" if _fcntl is not None else "msvcrt"


def _read_lines(p: Path) -> list[str]:
    if not p.exists():
        return []
    return [l for l in p.read_text(encoding="utf-8", errors="ignore").splitlines() if l.strip()]


def _unchanged(p: Path, expect: os.stat_result) -> bool:
    """Тот ли это файл и то ли в нём содержимое, по которому собран новый текст."""
    try:
        now = p.stat()
    except OSError:
        return False
    return ((now.st_ino, now.st_size, now.st_mtime_ns)
            == (expect.st_ino, expect.st_size, expect.st_mtime_ns))


def _write_lines(p: Path, lines: list[str], expect: os.stat_result | None = None) -> bool:
    """Переписать записку целиком — атомарной подменой, чтобы читатель не увидел половины.

    Читателей у неё трое (`read`, `said_recently`, через них — дайджест комнат), и они
    ходят без замка: подмена делает их безопасными бесплатно. `os.replace` на Windows
    может упереться в открытый читателем файл (CPython не даёт FILE_SHARE_DELETE) — тогда
    несколько коротких попыток, и в крайнем случае запись на месте: содержимое то же,
    теряется только атомарность для читателя.

    ⚠ `expect` — снимок `stat()` того состояния, ПО КОТОРОМУ собран `lines`. Прямо перед
    подменой файл пересматривается, и если он с тех пор изменился, подмены НЕ будет
    (False). Это не педантизм: 27.07 воспроизвели, как держатель замка схлопывал файл по
    своему устаревшему снимку и съедал строку, которую второй писатель успел положить мимо
    замка атомарным O_APPEND (слой 3). Пропажа молчаливая — в записке просто нет её слова.
    """
    data = ("\n".join(lines) + "\n").encode("utf-8")
    tmp = p.with_name(f".{p.name}.{os.getpid()}.{threading.get_ident()}.tmp")
    try:
        with open(tmp, "wb") as fh:
            fh.write(data)
        for attempt in range(5):
            if expect is not None and not _unchanged(p, expect):
                return False
            try:
                os.replace(tmp, p)
                return True
            except PermissionError:                # pragma: no cover — ветка Windows
                time.sleep(0.01 * (attempt + 1))
        if expect is not None and not _unchanged(p, expect):   # pragma: no cover — Windows
            return False
        with open(p, "wb") as fh:                  # pragma: no cover — ветка Windows
            fh.write(data)
        return True
    finally:
        try:
            os.unlink(tmp)
        except OSError:
            pass


def _collapse(p: Path, keep: int) -> bool:
    """Схлопнуть записку до последних `keep` ЗАПИСЕЙ — но только по СВЕЖЕМУ снимку.

    ⚠ 03.08.2026 здесь резалось по СТРОКАМ, и это было хуже, чем неудобное чтение:
    обломок ложился на диск. Прочитать целую запись после такого схлопывания было
    уже нечем — её половина стёрта из единственного места, где она была.

    Три захода: между чтением и подменой второй писатель мог дописать строку мимо замка,
    и тогда снимок устарел — схлопывать по нему нельзя, съест чужое слово. Не сошлось
    трижды — не схлопываем вовсе. Длинный файл не вредит никому (и `read`, и
    `said_recently` берут хвост), а потерянная строка — это её речь, которой потом не
    найдут ни дайджест комнат, ни свидетельство присутствия.
    """
    for _ in range(3):
        try:
            st = p.stat()                          # снимок берётся ДО чтения нарочно:
        except OSError:                            # так изменение во время чтения тоже видно
            return False
        lines = _read_lines(p)
        kept = _tail(lines, keep)
        if len(kept) >= len(lines):
            return True
        if _write_lines(p, kept, expect=st):
            return True
    return False


def _append_raw(p: Path, stamped: str) -> bool:
    """Дописать одну строку одним `os.write` в дескриптор с O_APPEND.

    Смещение при O_APPEND выбирается ядром в момент записи, поэтому дописывание НЕ
    способно затереть чужую строку даже без замка. Это дно, ниже которого запись не
    падает: даже когда межпроцессный замок недоступен, её слово всё равно на диске.

    ⚠ И это свойство ЯДРА POSIX, а не самой функции. На Windows `O_APPEND` живёт в CRT и
    разворачивается в «встать в конец, потом писать» двумя шагами — то есть дно там
    проседает, и защита держится на слоях 1-2. Измерено 27.07 на стенде: со снятыми
    верхними слоями 6 потоков × 20 строк дают 92 строки из 120. Она живёт на linux
    (`/app/memory` — bind-mount на ext4), гейт-образ тоже linux; Windows здесь только стенд,
    но врать про него в докстринге нельзя — прочтёт и поверит.

    Единственное, что может это дно пробить, — схлопывание СОСЕДА: он подменяет файл через
    `os.replace`, и наша строка остаётся в отцепленном inode. Поэтому после записи мы
    сверяем, тот ли файл лежит по пути; если подменили — смотрим, дожила ли строка, и при
    надобности кладём её заново. Отдаёт False, если так и не дожила: молча терять её слово
    нельзя даже здесь.
    """
    body = stamped.encode("utf-8")
    for _ in range(3):
        prefix = b""
        try:                       # старый файл мог остаться без перевода строки в конце —
            if p.stat().st_size:   # тогда дописывание склеило бы две её реплики в одну
                with open(p, "rb") as fh:
                    fh.seek(-1, os.SEEK_END)
                    if fh.read(1) != b"\n":
                        prefix = b"\n"
        except OSError:
            pass
        fd = os.open(str(p), os.O_WRONLY | os.O_CREAT | os.O_APPEND, 0o644)
        try:
            os.write(fd, prefix + body + b"\n")
            if _same_file(fd, p):
                return True
        finally:
            os.close(fd)
        if stamped in _read_lines(p):              # сосед схлопнул, но строку сохранил
            return True
        log.warning("записка [%s]: файл подменили под дописыванием — кладу строку заново",
                    p.name)
    return False


def append(chat_id: str | int, line: str) -> None:
    """Дописать строку в её записку по этому чату. ЕДИНСТВЕННЫЙ писатель этих файлов.

    ⚠ Здесь стоял голый read-modify-write: прочитать файл, дописать строку, записать
    целиком обратно. Пока писал один контур (голос), это сходило с рук. 27.07 писателей
    стало двое — к голосу добавилась проекция прямой отправки, и она идёт в ОТДЕЛЬНОМ
    потоке (`asyncio.to_thread` в реконсиляции outbox). Живой сценарий: она отвечает
    голосом в комнату, и одновременно пульс отправляет прямую реплику; оба читают одну
    версию файла, оба пишут свою — одна строка исчезает. Репро: 6 потоков × 40 записей
    оставляли в файле 24 строки из 240, два процесса — 36 из 300.

    Три слоя, и они разной прочности НАМЕРЕННО:
      1. `_writer_lock(p)` — потоковый замок на эту записку. Работает всегда и везде;
         сегодняшняя гонка живёт внутри одного процесса, так что слой закрывает её целиком.
      2. межпроцессный замок на соседнем `.lock` — для случая «писатели в разных
         процессах» (praxis и praxis-mailbot делят `./:/app` на запись). Он покупает ровно
         одно право: СХЛОПНУТЬ файл, не съев чужую строку. Нет его — нет и схлопывания.
      3. `O_APPEND`-дописывание. Оно идёт ВСЕГДА и первым, а не только когда замка нет:
         так её собственная строка не зависит ни от снимка файла, ни от исхода возни с
         замком. На POSIX ядро выбирает смещение в момент записи и затереть чужое нечем;
         на Windows (только стенд) это свойство слабее — см. `_append_raw`.

    ⚠ Про СМЕШАННУЮ гонку (один писатель под замком, второй мимо замка). Здесь стояло, что
    строка второго при этом исчезает — так и было, воспроизвели. Теперь этого пути нет:
      • свою строку держатель тоже кладёт `O_APPEND`-ом, а не перезаписью файла целиком,
        так что она не зависит от того, изменился ли файл под ним;
      • схлопывание идёт только по снимку, который не устарел (`_collapse`/`_write_lines`
        сверяют `stat` прямо перед подменой), а не сошлось — файл остаётся длинным, и об
        этом пишется в лог;
      • дописывание само проверяет, не подменили ли файл под ним (`_append_raw`).
    Что сказать всё-таки нельзя: «потери нет НИКОГДА». Осталось окно между тем, как
    дописывающий убедился, что файл под ним не подменили, и подменой, которую держатель
    делает следом: строка, попавшая ровно туда, пропадёт — и пропадёт молча. Окно сузилось
    с миллисекунд (чтение и перезапись файла целиком) до двух системных вызовов подряд, но
    оно есть, и без замка у ОБОИХ писателей закрыть его нечем. Всё, что шире этого окна,
    ловится: строка кладётся заново, а если и это не вышло — в лог уходит ERROR с самой
    строкой, чтобы её можно было найти.
    """
    line = (line or "").strip()
    if not line:
        return
    SCRATCH_DIR.mkdir(parents=True, exist_ok=True)
    p = path_for(chat_id)
    stamped = f"{_local_now():%H:%M} · {line}"
    with _writer_lock(p):
        with _exclusive(p) as lock:
            # Слой 3 идёт ПЕРВЫМ и всегда — чем бы ни кончилась возня с замком ниже, её
            # строка уже на диске и никого не затирает. Раньше держатель клал её
            # перезаписью файла целиком, то есть её слово зависело от чужих записей.
            if not _append_raw(p, stamped):
                log.error("записка [%s]: строка не легла даже дописыванием, потеряно: %r",
                          p.name, stamped)
            if lock.owned and not lock.intact():
                # `.lock` удалили или подменили, пока мы его держали: другой писатель уже
                # взял «свободный» замок на новом файле, взаимного исключения больше нет.
                # Схлопывать в такой момент — это ровно тот способ съесть чужую строку.
                log.warning("записка [%s]: файл замка исчез или подменён, пока я его "
                            "держала — взаимное исключение снято, файл не схлопываю",
                            p.name)
                return
            if lock.owned:
                if not _collapse(p, MAX_ENTRIES):
                    log.warning("записка [%s]: файл менялся под замком — не схлопнула, "
                                "чтобы не съесть чужую строку; строк сейчас %d",
                                p.name, len(_read_lines(p)))
                return
            extra = _read_lines(p)
            if len(extra) < MAX_ENTRIES * _UNLOCKED_TRIM_FACTOR:
                # Причину `_acquire` уже назвал — отдельно звать `lock_kind()` нельзя:
                # диагностика сама берёт замок и ждёт, а это путь каждой её реплики.
                log.warning("записка [%s]: межпроцессный замок не взят (%s) — строка "
                            "дописана, файл не схлопнут", p.name,
                            lock.why or "причина не названа")
                return
            # Файл разросся, а замка так и нет. Схлопываем — но тем же способом «только по
            # свежему снимку»: без замка чужая одновременная строка тем более беззащитна.
            log.warning("записка [%s]: %d строк без межпроцессного замка (%s) — схлопываю "
                        "перезаписью по свежему снимку; не сойдётся — останется длинным",
                        p.name, len(extra), lock.why or "причина не названа")
            _collapse(p, MAX_ENTRIES)


def _norm(s: str) -> str:
    """Нормализация для сравнения по сути: без регистра, пунктуации и лишних пробелов."""
    return re.sub(r"\s+", " ", re.sub(r"[^\w\s]", "", (s or "").lower(), flags=re.UNICODE)).strip()


def _similar(gist: str, text: str) -> bool:
    """Похоже ли новое (text) на уже сказанное (gist)? gist может быть обрезан до SAID_GIST_CHARS,
    поэтому сравниваем и включение, и близость на сопоставимой длине."""
    g, t = _norm(gist), _norm(text)
    if not g or not t:
        return False
    if g in t or t in g:
        return True
    head = t[: len(g) + 12]
    return difflib.SequenceMatcher(None, g, head).ratio() >= _SIMILAR_THRESHOLD


def said_recently(chat_id: str | int, text: str,
                  max_entries: int = MAX_ENTRIES) -> bool:
    """Говорила ли она это (близко по форме) недавно в этом МЕСТЕ — СПРАВКА, не запрет.

    Из боевого кода не вызывается ни разу (см. докстринг модуля: блокирующая форма снята
    сознательно). Ответ ровно настолько полон, насколько полна записка: сказанное мимо
    того пути, который пишет `сказала: «…»`, для этой функции не существовало вовсе —
    отсюда «нет» будет и на дословный повтор, если строки о первой отправке в записке нет.

    Смотрит цитаты «…» в записках — туда пишется суть сказанного. Соседние ветки одного
    места читаются тоже: пока ключ расщеплялся, её «сказала…» из соседней ветки того же
    чата была ей не видна, и анти-повтор работал вслепую. Порядок строк здесь не нужен — вопрос
    «говорила ли», а не «в каком порядке», поэтому и сортировать нечего.
    """
    if not (text or "").strip():
        return False
    for path in _sibling_files(chat_id):
        if not path.exists():
            continue
        lines = [l for l in path.read_text(encoding="utf-8", errors="ignore").splitlines()
                 if l.strip()]
        for group in _entries(lines)[-max_entries:]:
            # ⚠ Цитата искалась ПОСТРОЧНО. Её реплика открывает «…» на первой строке и
            # закрывает на третьей, поэтому ни одна строка не содержала пары целиком, и
            # `_QUOTE_RE` не находил ничего. Проба 03.08 на её живом файле: её же слова,
            # поданные обратно дословно, дали False. Слепота покрывала 52% её записей —
            # то есть большинство того, о чём эта справка и должна отвечать.
            for gist in _QUOTE_RE.findall("\n".join(group)):
                if _similar(gist, text):
                    return True
    return False
