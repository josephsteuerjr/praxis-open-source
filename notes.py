# Замок СВОЙ НА КАЖДУЮ записку, а не один общий: общий означал бы, что чужой процесс,
# застрявший на одном чате, придерживает её голос во всех остальных — молчаливая задержка
# там, где её никто не ждёт.
_WRITERS_GUARD = threading.Lock()
_WRITERS: dict[str, threading.RLock] = {}


def _writer_lock(p: Path) -> threading.RLock:
    key = str(p)
    with _WRITERS_GUARD:
        lock = _WRITERS.get(key)
        if lock is None:
            lock = _WRITERS[key] = threading.RLock()
        return lock

