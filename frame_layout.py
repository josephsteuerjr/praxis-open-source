def quote(text: str) -> str:
    """Чужое ТЕЛО под гуттером. Считает обезвреженные строки — их у непустого тела не 0.

    ⚠ ПРЕДМЕТ СЧЁТЧИКА ИЗМЕНИЛСЯ, И ЭТО ГЛАВНОЕ. Прежний `sanitized_lines` считал, сколько
    подделок ПОЙМАЛИ, — и все семь живых обходов прошли при нуле, потому что ноль означал
    сразу и «чисто», и «замок не увидел». `gutter_lines` считает, сколько строк ОБЕЗВРЕЖЕНО;
    у непустого тела он никогда не ноль, и тихий ноль как признак взлома исчезает вместе с
    классом «замок посмотрел и не увидел».
    """
    out = gutter.quote(text)
    _bump("gutter_lines", out.count("\n") + 1 if out else 0)
    return out


def inline(value: object) -> Own:
    """Чужое ЗНАЧЕНИЕ в нашей строке. Единственный производитель пары `«»` в кадре.

    Зовут СТОКИ, а не источники: `_place`, `_speaker`, `_working`, каждый чужой фасет
    `origin()` и всякий слот `delivery()` вне закрытого `DELIVERY_CAUSES`. Перечисление
    ИСТОЧНИКОВ и было предыдущей ошибкой — в другом масштабе.
    """
    result = gutter.inline(value)
    if result:
        _bump("inline_slots")
    return result


def _own(value: object) -> Own:
    """Что угодно -> `Own`. Забывчивость стоит лишних кавычек, а не дыры.

    Под PRAXIS_FRAME_STRICT сырой `str` в склейке — `TypeError` на месте вызова: так забытый
    сток находится на стенде, а не в кадре. В проде он молча уходит в `inline()`: лишние
    кавычки вокруг нашего литерала уродливы, а несобравшийся кадр — немота.
    """
    if isinstance(value, Own):
        return value
    if value is None or value == "":
        # Пустой слот — это ОТСУТСТВИЕ слота, а не забытый сток: обезвреживать нечего и
        # ронять не за что. Умолчания `key=""`/`selection=""` живут ровно здесь.
        return own("")
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        return own(value)
    if strict():
        raise TypeError("склейка кадра получила сырой str: " + repr(value)[:120])
    return inline(value)


