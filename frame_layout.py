def stash(**facts) -> None:
    """Сложить наблюдённый факт в снимок текущего хода. Никогда не бросает.

    Существует ради ОДНОГО запрета: зона «СЕЙЧАС» не имеет права ходить на диск. Профиль
    комнаты читается за кадр уже трижды (agent.py 7147, 7259, 7268) и совпадение содержимого
    внутри одного кадра не гарантировано — это записано в докстринге прибора. Четвёртая
    версия правды о комнате в кадре, который чинили ради правды, была бы прямым откатом.
    Поэтому сборщик кладёт сюда то, что УЖЕ прочитал, а зона только читает.
    """
    try:
        snap = _SNAP.get()
        if snap is None:
            snap = {}
            _SNAP.set(snap)
        snap.update(facts)
    except Exception:
        pass


def snapshot() -> dict:
    try:
        return dict(_SNAP.get() or {})
    except Exception:
        return {}


def reset() -> None:
    """Начать снимок заново. Зовётся один раз за кадр, на входе в сборку."""
    try:
        _SNAP.set({})
    except Exception:
        pass


def begin(**facts) -> None:
    """`reset` + `stash` одним вызовом — первая точка сборки кадра.

    Существует ради счётчиков формы: `gutter_lines`, `inline_slots` и `unnamed_cause`
    накапливаются внутри снимка, а нить живёт дольше одного хода. Без явного начала кадра
    число обезвреженных строк поехало бы суммой за всю жизнь процесса — то есть прибор врал
    бы ростом.
    """
    reset()
    stash(**facts)


def _bump(key: str, delta: int = 1) -> int:
    """Накопитель счётчиков формы внутри снимка (гуттер, стоки, безымянные причины)."""
    try:
        snap = _SNAP.get()
        if snap is None:
            snap = {}
            _SNAP.set(snap)
        value = int(snap.get(key) or 0) + int(delta)
        snap[key] = value
        return value
    except Exception:
        return 0


