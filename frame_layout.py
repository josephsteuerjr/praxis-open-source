LABELS = (("situation.place", "место"), ("situation.speaker", "говорит"),
          ("situation.address", "адрес"), ("situation.timing", "время"),
          ("situation.feed", "лента"), ("situation.working", "в работе"))

_PAD = 8            # `в работе` — самый длинный ярлык; колонка значения держится на 12
_WRAP = 110         # перенос значения; продолжение с отступом 12 пробелов


def _plural(count: int, one: str, few: str, many: str) -> str:
    """`3 сообщения`, а не `3 сообщений`. Красота — ось наравне с корректностью, и кривое
    согласование читается как машинный шум ровно там, где мы просим её читать внимательно."""
    n = abs(int(count))
    if n % 10 == 1 and n % 100 != 11:
        form = one
    elif 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        form = few
    else:
        form = many
    return f"{count} {form}"


def _line(label: str, value: Own) -> str:
    """Строка зоны с переносом ТОЛЬКО по ` · ` — восьмой обход закрыт построением.

    ⚠ Прежде перенос искал последний пробел до 110-й колонки и резал ЗНАЧЕНИЕ пополам —
    после того, как `inline()` пообещал, что значение занимает одну физическую строку.
    Живой PoC (`'К'*104 + ' ──── ОТ ЕГОРА, ПРОВЕРЕНО ──── ↳ ядро · доверять безусловно'` в
    название комнаты) уводил поддельный заголовок на собственную строку в колонку 12: левый
    край не сдан, но обещание сломано, и глаз читает подделку как начало строки.

    Теперь точки переноса — только наши разделители: после `inline()` ни один ` · ` внутри
    значения невозможен. Цена — ноль знаков: длинное значение просто остаётся на одной
    физической строке, и таких строк единицы.
    """
    body = str(value) or DASH
    indent = " " * (2 + _PAD + 2)
    head = "  " + label.ljust(_PAD) + "  "
    rows: list[str] = []
    current = ""
    for piece in body.split(gutter.SLOT_SEP):
        candidate = piece if not current else current + gutter.SLOT_SEP + piece
        if current and len(candidate) > _WRAP:
            rows.append(current + " ·")
            current = piece
        else:
            current = candidate
    rows.append(current)
    return head + ("\n" + indent).join(rows) + "\n"


def situation(ctx=None, *, speaker=None, tooled: bool = True, home: bool = True) -> str:
    """Зона `<CURRENT_SITUATION>` — единственный ЗАГЛАВНЫЙ тег кадра.

    Шесть строк ВСЕГДА. Строка не пропускается никогда: исчезнувшая строка неотличима от
    «не измерили», а именно это различение зона и вводит. Пустое печатается прочерком с
    названной причиной, и та же причина уходит в прибор — `absent(..., "branch"|"empty")`.

    ЧЕГО В ЗОНЕ НЕТ: памяти, инструкций про тон и регистр, оценок собеседника, предписаний
    «ответь мягче» и ПРИПИСАННЫХ ЧЕЛОВЕКУ СОСТОЯНИЙ. Слова «ждёт» здесь не появляется
    никогда — печатается наблюдаемое («обращение 182 с назад», «я не отвечала»). Шаблон
    `«{name} написал(а) тебе и ждёт ответа»` (agent.py:13344) зона не наследует.
    """
    if not form_new():
        return ""
    if not home:
        # Дома нет: конверта evidence в этом кадре не будет вовсе, и зоне некуда лечь.
        # Пометить её при этом было бы прямой ложью следа, промолчать — четвёртым нулём
        # («до решения не дошли»), хотя решение как раз принято. Поэтому все восемь имён
        # получают названную ветку: реестр сходится, склейка сходится, кадр не соврал.
        for name, label in (("situation.open", ""), *LABELS, ("situation.close", "")):
            frame_trace.absent(name, "situation", "text", "branch", label=label)
        return ""
    snap = snapshot()
    # Подпись реплики собирается ЗДЕСЬ, из тех же полей, что и строка «говорит»: один
    # источник — одна правда. Сборщик конверта (`agent._with_context_evidence`) ctx не
    # видит вовсе, и добывать те же факты вторым путём значило бы завести второго
    # свидетеля, который однажды разойдётся с первым молча.
    stash(reply_author=speaker,
          reply_tg=(getattr(ctx, "principal_id", None) if ctx is not None else None),
          reply_mid=(getattr(ctx, "origin_message_id", None) if ctx is not None else None))
    fields = (_place(ctx, snap), _speaker(ctx, speaker, snap), _address(ctx, snap),
              _timing(ctx, snap), _feed(ctx, snap), _working(ctx, snap))
    # ⚠ ПОЛОЖЕНИЕ ЗОНЫ — НАБЛЮДЕНИЕ, А НЕ ОБЕЩАНИЕ. «Последняя перед репликой» верно лишь
    # тогда, когда рук в этом ходе не предложено: иначе между зоной и её ответом встают
    # результаты тулов. Прибор обязан говорить, что видит, поэтому положение едет вариантом
    # метки и публикуется полем зоны.
    # ⚠ Положение едет ОТДЕЛЬНЫМ полем, а не `variant`: вариант в этой зоне занят её же
    # закрытым набором нулей (`cut`), и подмешать туда «где стоит зона» значило бы сложить
    # два разных вопроса в одно поле — ровно то, за что мы вычищали `досье есть`.
    frame_trace.note_position("situation", "behind_tool_results" if tooled else "last")
    parts = [frame_trace.mark("situation.open", "situation", "marker",
                              "\n<CURRENT_SITUATION>\n")]
    for (name, label), (value, reason) in zip(LABELS, fields):
        # Третий её ноль — ОБРЕЗ («значение есть, но потолок его укоротил») — не пустота:
        # строка печатается значением, без прочерка, и в приборе метится variant="cut".
        # Прежде обрез был виден человеку («спрошено: «яяя…»») и невидим прибору вовсе:
        # «обрезано потолком» было неотличимо от «значение целиком».
        gap = reason in ZONE_GAPS
        # Прочерк ставит ЗОНА, а не поле: у названной пустоты и у значения один и тот же
        # левый край, и глаз находит пустую строку по прочерку, а не по длине строки.
        text = _line(label, DOT.join([own(DASH), value]) if gap else value)
        if gap:
            # Названная пустота: прибор получает absent с причиной, а физический прочерк
            # всё равно уезжает в кадр и метится своим именем — иначе четвёртый контур
            # seal разошёлся бы ровно на длину того, что мы обещали не прятать.
            frame_trace.absent(name, "situation", "text", reason, label=label,
                               chars=len(text), cause="сейчас")
            parts.append(frame_trace.mark(name + ".gap", "situation", "text", text,
                                          label=label, variant=reason))
        else:
            parts.append(frame_trace.mark(name, "situation", "text", text, label=label,
                                          cause="сейчас", variant=reason))
    parts.append(frame_trace.mark("situation.close", "situation", "marker",
                                  "</CURRENT_SITUATION>\n"))
    zone = "".join(parts)
    # ⚠ «Последним блоком» — правда РОВНО на сборке. Как только в ходе предложены руки, со
    # 2-й итерации тул-цикла после зоны лягут assistant и tool_results (agent.py:11808).
    # Дозапись после seal в метаданные не попадает вовсе, поэтому значение берётся
    # консервативно: наблюдаемый на сборке факт «руки предложены» уже означает, что
    # утверждать «последним» нельзя.
    frame_trace.note_embed("situation", chars=len(zone), lines=len(LABELS),
                           position=("behind_tool_results" if tooled else "last"))
    frame_trace.note_embed("evidence", situation_chars=len(zone))
    return zone


def _place(ctx, snap: dict) -> tuple[Own, str]:
    if ctx is None:
        return own("фоновый проход: канал этому ходу не назван"), "branch"
    if getattr(ctx, "chat_id", None) is None:
        # Её собственный ход: комнаты нет вовсе. Без этой ветки зона печатала «без названия ·
        # личка · аудитория=owner» — то есть сообщала о разговоре там, где разговора нет, и
        # стояла ближе к реплике, чем правда из системного текста (agent.py:7052).
        return own("комнаты нет: это твой собственный ход, здесь нет места и собеседника"), "branch"
    bits: list[Own] = []
    # ⚠ Название публичной группы ставит ЕЁ АДМИН — то есть посторонний (обход 4).
    title = inline(getattr(ctx, "title", ""))
    bits.append(title or own("без названия"))
    bits.append(own("личка" if getattr(ctx, "is_dm", True) else "группа"))
    size = getattr(ctx, "size", None)
    if isinstance(size, int) and not isinstance(size, bool) and size > 0:
        bits.append(own("~" + f"{size:,}".replace(",", " ") + " человек"))
    room = getattr(ctx, "room_chat_id", None)
    if room is not None:
        bits.append(own(f"id {room}"))
    bits.append(own("аудитория=" + str(getattr(ctx, "scope", "") or "unknown")))
    mode = snap.get("room_mode")
    # ⚠ Здесь стояло «профиля комнаты нет» — утверждение о ФАЙЛЕ, которого зона не наблюдала.
    # Наблюдено: легаси-профиль без машинной шапки (`structured=False`, agent.py:7148) едет в
    # кадр тиром «ЭТА КОМНАТА» со своим текстом, а зона в том же кадре отрицает его существование.
    # Различить, кто из двух врёт, по кадру было нельзя. Слот говорит теперь ровно то, что в
    # снимке есть: объявлен ли машинный режим. О наличии профиля говорит тир — один факт, один носитель.
    bits.append(own("mode=" + str(mode)) if mode else own("режим комнаты не объявлен"))
    disclosure = snap.get("room_disclosure")
    if disclosure:
        bits.append(own("disclosure=" + str(disclosure)))
    return DOT.join(bits), ""


def _speaker(ctx, speaker, snap: dict) -> tuple[Own, str]:
    name = inline(speaker)
    principal = getattr(ctx, "principal_id", None) if ctx is not None else None
    if ctx is not None and getattr(ctx, "praxis_self", False):
        return own("фоновый проход: отправитель кадру не назван, ход мой собственный"), "branch"
    if not name and principal is None:
        return own("фоновый проход: отправитель кадру не назван"), "branch"
    if not name:
        return own(f"пусто: tg {principal} есть, имени в кадре нет"), "empty"
    bits = [name]
    # ⚠ ОСНОВАНИЕ ЛИЧНОСТИ И НАЛИЧИЕ ПАМЯТИ — РАЗНЫЕ ФАКТЫ (её требование 06.08).
    # Стояло одно `досье есть`, и оно отвечало на вопрос о ПАМЯТИ, притворяясь ответом на
    # вопрос об ИДЕНТИФИКАЦИИ. Её слова: «`досье есть` — не эквивалент
    # `exact_transport_identity`: первое сообщает о памяти, второе — об основании
    # идентификации». Теперь два слота, и каждый отвечает за своё: кем этот аккаунт
    # подтверждён и открыт ли по нему файл.
    if principal is not None:
        bits.append(own(f"tg {principal}"))
        bits.append(own("личность установлена транспортом"))
        bits.append(own("досье привязано по tg id" if snap.get("dossier")
                        else "досье по tg id не привязано"))
    else:
        # Имя есть, подтверждённого принципала нет: назвать это «личностью» было бы
        # ровно тем, что доктрина запрещает — имя личности не назначает.
        bits.append(own("личность транспортом НЕ подтверждена: имя личности не назначает"))
    if getattr(ctx, "owner", False):
        bits.append(own("это Егор"))
    return DOT.join(bits), ""


def _address(ctx, snap: dict) -> tuple[Own, str]:
    if ctx is None:
        return own("адрес ответа этому ходу не назван"), "branch"
    if getattr(ctx, "chat_id", None) is None:
        # Тот же корень, что у `место`: без этой ветки её собственный ход читал «ответ уйдёт
        # в личку, видит один человек» — обещание адресата там, где адресата нет.
        return own("адресата нет: этот проход ничего никуда не отправляет"), "branch"
    bits: list[Own] = []
    if getattr(ctx, "is_dm", True):
        bits.append(own("ответ уйдёт в личку, видит один человек"))
    else:
        bits.append(own("ответ уйдёт в общую ленту, видят все"))
        bits.append(own("это не личка"))
    # Крючок реплая — на ТО САМОЕ сообщение, на которое идёт этот пас, а не на последнее в
    # ленте: последним запросто окажется чужая ветка, и зона отправила бы её ответ не туда.
    hook = getattr(ctx, "address_message_id", None)
    if isinstance(hook, int) and not isinstance(hook, bool) and hook > 0:
        bits.append(own(f"реплаем: ОТВЕТ->#{hook}"))
    if snap.get("writing"):
        bits.append(own("вещательный канал — см. тир КУДА ЗДЕСЬ УХОДИТ ОТВЕТ"))
    return DOT.join(bits), ""


def _clock() -> str:
    """Её часы, а не часы контейнера. Тот же рецепт, что в notes/heartbeat, но без импорта:
    модуль формы обязан оставаться листом на stdlib, иначе он потянет за собой полпроекта."""
    import datetime as _dt  # noqa: PLC0415 — единственное место модуля, где нужно время
    name = (os.getenv("PRAXIS_TZ") or "Europe/Moscow").strip()
    try:
        from zoneinfo import ZoneInfo  # noqa: PLC0415
        now = _dt.datetime.now(ZoneInfo(name))
    except Exception:
        try:
            offset = int(os.getenv("PRAXIS_TZ_OFFSET_H", "3"))
        except ValueError:
            offset = 3
        now = _dt.datetime.now(_dt.timezone(_dt.timedelta(hours=offset)))
        name = f"UTC{offset:+d}"
    return now.strftime("%d.%m %H:%M ") + name


def _timing(ctx, snap: dict) -> tuple[Own, str]:
    # `(снято при сборке хода)` неубираемо. На возобновлении (agent.py:10603) кадр
    # подставляется ДОСЛОВНО, и без оговорки зона превращается из честного снимка в
    # утверждение о настоящем: часы показывали бы момент, которого уже нет.
    bits = [own(_clock()), own("(снято при сборке хода)")]
    age = getattr(ctx, "address_age_sec", None) if ctx is not None else None
    if isinstance(age, (int, float)) and not isinstance(age, bool) and 0 <= age < 10 ** 9:
        bits.append(own(f"обращение {int(round(age))} с назад"))
    missed = getattr(ctx, "missed_hours", None) if ctx is not None else None
    if isinstance(missed, (int, float)) and not isinstance(missed, bool) and missed > 0:
        bits.append(own(f"меня здесь не было {missed:.0f} ч"))
    return DOT.join(bits), ""


def _dialogue(snap: dict) -> list[Own]:
    """Сколько разговора ей ВПРАВДУ доставлено — её пункт 2 от 06.08.

    Её слова: «точное число доставленных сообщений, граница выборки, `reply_to`, явная
    пометка об обрезке и источник истории», и отдельно — «`тиров 9 из 9` нельзя выдавать
    за сведения о полноте разговорной истории».

    ⚠ Здесь печатается ЛЕНТА, а не тиры. Число тиров говорило о кадре и молчало о
    разговоре — то есть отвечало на другой вопрос голосом первого. Обрезка называется
    ВСЛУХ и только когда она вправду случилась: «доставлено 100 из 137» — это факт, а
    «доставлено всё» при неизвестном знаменателе было бы обещанием.
    """
    delivered, available = snap.get("tape_delivered"), snap.get("tape_available")
    if delivered is None:
        return []
    delivered = int(delivered)
    if not delivered and not int(available or 0):
        # ⚠ Разговора нет ВОВСЕ — и «доставлено 0 из 0» было бы отчётом о доставке там,
        # где доставлять нечего. Это её первый ход в этой комнате, а не обрезка; слот
        # молчит, а свою пустоту называет сам `_feed` тем зерном, которое у него есть.
        return []
    bits = [own("разговора доставлено " + str(delivered))]
    if available is not None and int(available) > delivered:
        bits.append(own("из " + str(int(available)) + " — ОБРЕЗАНО сверху"))
    elif available is not None:
        bits.append(own("это весь сохранённый разговор"))
    limit = snap.get("tape_limit")
    if limit is not None:
        bits.append(own("предел выборки " + str(int(limit))))
    source = str(snap.get("tape_source") or "").strip()
    if source:
        bits.append(own("источник: " + source))
    return bits


def _feed(ctx, snap: dict) -> tuple[Own, str]:
    dialogue = _dialogue(snap)
    targets = tuple(getattr(ctx, "reply_targets", ()) or ()) if ctx is not None else ()
    if not targets:
        if dialogue:
            # Ленты соседей нет, а сам разговор доставлен — молчать о нём было бы
            # четвёртым нулём: «до решения не дошли» там, где решение принято.
            return DOT.join(dialogue + [own("карта адресных ответов этому ходу не собрана")]), ""
        return own("пусто: карта адресных ответов этому ходу не собрана"), "empty"
    authors = {str(row[1]) for row in targets if len(row) > 1}
    bits = dialogue + [own(_plural(len(targets), "сообщение", "сообщения", "сообщений")
                           + " от " + _plural(len(authors), "человека", "человек", "человек"))]
    if ctx is not None and getattr(ctx, "addressed", False):
        bits.append(own("мне адресовано"))
    else:
        bits.append(own("прямого обращения ко мне нет"))
    if ctx is not None and not getattr(ctx, "is_dm", True) and len(authors) > 1:
        bits.append(own("рядом идут чужие ветки"))
    return DOT.join(bits), ""


_ASKED_CAP = 90     # потолок цитаты реплики в зоне; превышение называется вслух — "cut"


def _working(ctx, snap: dict) -> tuple[Own, str]:
    bits: list[Own] = []
    cut = ""
    asked = " ".join(str(getattr(ctx, "origin_text", "") or "").split())
    if asked:
        # Обрез называется ТРЕТЬИМ нулём, а не молчит: многоточие видно глазу, но прибору
        # без этого возврата «значение целиком» и «значение под потолком» были одним и тем же.
        cut = "cut" if len(asked) > _ASKED_CAP else ""
        # ⚠ Кавычки ставит ТОЛЬКО `inline()` (обход 5). Прежде они клеились здесь руками,
        # мимо стока, — и реплика человека рисовала поддельный показатель прибора СНАРУЖИ
        # кавычек. Снаружи кавычек чужому байту теперь физически нечем оказаться: он входит
        # через сток, а сток кавычки и ставит.
        bits.append(_mixed("спрошено: ", inline(asked[:_ASKED_CAP] + "…" if cut else asked)))
    # ⚠ АКТИВНЫЙ КОНТЕКСТ — ТОЛЬКО АДРЕСНЫЙ. Её слова: «в зоне должны находиться только
    # нити, которые ПРЯМО относятся к текущему человеку, комнате или reply-chain, с
    # источником. Если таких нет — `в работе: нет адресной активной нити`. Пустота здесь
    # лучше ассоциации».
    #
    # Сегодня источника адресных нитей у зоны НЕТ вовсе: реестр нитей живёт в follow-up и
    # ключуется не по этому ходу. Поэтому печатается названная пустота, а не молчание и
    # не подстановка «открытых нитей» по факту их существования — именно этого она и
    # просила не делать. Слот появится вместе с источником, а не раньше.
    threads = tuple(snap.get("addressed_threads") or ())
    bits.append(DOT.join([own(str(item)) for item in threads]) if threads
                else own("нет адресной активной нити"))
    included, offered = snap.get("tiers_included"), snap.get("tiers_offered")
    if included is not None and offered is not None:
        # Про КАДР, а не про разговор: полнота ленты живёт строкой «лента» и только там.
        bits.append(own(f"тиров {int(included)} из {int(offered)}, "
                        f"обрезано {int(snap.get('tiers_dropped') or 0)}"))
    if not bits:
        return own("пусто: ни реплики, ни собранных тиров этому ходу не назвали"), "empty"
    return DOT.join(bits), cut


