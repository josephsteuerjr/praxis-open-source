"""Форма кадра: как её контекст выглядит, когда его читают глазами.

Первый модуль проекта, который меняет кадр РАДИ ФОРМЫ, а не ради правды. До него все
правки кадра чинили то, что в нём было сказано неверно; здесь всё сказанное остаётся тем
же, а меняется расположение и подпись.

Три слоя, по одному вопросу на каждый:

1. СЕКЦИЯ (`section`) — «где кончается один кусок и начинается другой». Было
   `json.dumps({"label": …, "content": …})`: одна физическая строка на весь тир,
   `\\n` вместо переносов, `\\"` вместо кавычек. Стало — правило, заголовок капсом,
   подпись, пустая строка, тело под гуттером.
2. ПОДПИСЬ (`delivery`) — «почему это здесь и каким путём попало». Пишет СБОРЩИК.
3. ПРОИСХОЖДЕНИЕ (`origin`) — «кто это сказал, когда и где лежит». Пишет ИСТОЧНИК.

⚠ ДВА ПЕРА, ДВЕ ПОЗИЦИИ. Сборщик пишет ТОЛЬКО в строку `↳`; источник — ТОЛЬКО в квадратные
скобки паспорта находки. Пересечение запрещено: как только delivery начнёт подмешиваться в
intrinsic, «пятый вопрос кадра» (почему это передо мной) станет неотличим от четвёртого
(что было), а именно ради их различения вся работа и делалась.

⭐ ЗАМОК ОПИСЫВАЕТ НАШЕ, А НЕ ОПАСНОЕ. Снятие `json.dumps` убрало экранирование ПО
ПОСТРОЕНИЮ и заменило его ПЕРЕЧИСЛЕНИЕМ опасных начал (`────`, `↳`, `- [`,
`[TRUST CONTRACT] `, теги конверта). Перечисление дополнялось трижды и трижды считалось
полным; семь живых обходов подряд входили мимо него — нагрузкой в одну строку без `\\n`,
разрывом `\\r`, невидимым `U+200B`, названием чужой комнаты, репликой человека, именем
файла со скобкой, запросом recall. Класс дефекта был один: замок СМОТРЕЛ и НЕ ВИДЕЛ, а
счётчик при этом честно показывал ноль.

Здесь список опасных начал снят целиком и не заменён другим. Чужой байт входит в кадр
ровно ДВУМЯ стоками, и оба живут в `gutter.py`:

* :func:`gutter.quote` — многострочное ТЕЛО: каждая строка получает `"> "`, экранные
  разрывы уезжают в имя метки и физически исчезают;
* :func:`gutter.inline` — одно ЗНАЧЕНИЕ в нашей строке: `«…»`, изнутри которых нечем
  закрыться, разделитель слотов недостижим, разрыв поднят в видимую метку `⟨CR⟩`.

Третьей двери нет, и это проверяется не перечислением каналов, а :func:`assay` на СОБРАННОМ
документе: всякая физическая строка кадра либо ПРОИЗВЕДЕНА нашим стоком (`gutter.is_gutter_line`
разбирает её и собирает обратно), либо дословно совпадает со строкой, которую эмиттер объявил
через `frame_trace.mark`/`declare`. Проверка по первому знаку `>` была бы тем же
перечислением: сток выдаёт шесть форм, а первый знак угадывает одну. Поэтому
канал, который завтра появится и о котором здесь не написано, краснит стенд сам, без
правки списка — списка нет.

⚠ ОСТАТОК НАЗВАН ВСЛУХ. Под гуттером байты `</CURRENT_SITUATION>` и `────` ВЫЖИВАЮТ:
гарантия ПОЗИЦИОННАЯ (гость не занимает левый край и не закрывает «…»), а не
содержательная. Это цена дословности её памяти, принятая ею на снимке прогона.
Подделка в СЕРЕДИНЕ длинной строки гуттером не снимается и мерится адверсаркой на живом
мозге, а не тестом.

⚠ ДЕВЯТОГО ЗНАЧЕНИЯ НЕТ. Словарь причин закрыт восемью токенами. Неизвестный ярлык даёт
`причина не названа` и поднимает `unnamed_cause`. Молчаливое «прочее» убило бы пятый вопрос
тихо — здесь это обязано быть неудобно.

⚠ Слот `рука` (поднято её рукой) сегодня ПУСТ: явный recall уходит `tool_result`'ом мимо
зоны evidence. Форма для него готова, данных нет, и это названо вслух, а не замазано.

Зависимости — только stdlib, `frame_trace` и `gutter`. Импорт `agent` запрещён ровно по той
же причине, что и у прибора: модуль, формирующий кадр, не имеет права зависеть от того, что
он формирует. Всё, что приходит из agent, приходит АРГУМЕНТОМ либо через снимок `stash`.

⚠ ЦЕНА ГУТТЕРА ЗАМЕРЕНА, А НЕ ОБЕЩАНА, И ОНА ОТРИЦАТЕЛЬНА. Зона evidence — 18 770 знаков в
личке (25 013 в группе), не 90 000: девяносто тысяч — это ВЕСЬ кадр. При плотности её прозы
89,2 знака на строку гуттер стоит ≈ 368 знаков (личка) / 490 (группа), легенда 95, кавычки
чужих фасетов паспорта 96, реплика под гуттером +314 — ИТОГО ≈ 873 знака на ход, то есть
4,7 % зоны evidence и 0,78 % кадра. Старая форма `json.dumps` стоила +1 300…2 500 знаков
чистого экранирования на ход, и новая форма их уже сняла: гуттер дешевле того, что и так
выброшено. Развилка «гуттер только на недоверенных телах» отклонена ЗАМЕРОМ: код пишет 3
тела из 14 (~51 строка, экономия ~102 знака = 0,5 % зоны), а покупается за это второй
перечень, обязанный вечно совпадать с первым. Либо гуттер тотален, либо мы снова считаем,
что перечислили всё.

⚠ ЗАМЕР НА СТЕНДЕ ДЕВЯТИ ТИРОВ (`test_now_zone.nine_tiers`) — число, а не обещание: форма
стоит **+1693 знака** на `messages[-1]`, из них зона «СЕЙЧАС» 638 и провенанс evidence 1053
(в том числе подписи сборщика 893). Прежние +1401 относились к форме БЕЗ гуттера: +292 —
это его цена на стенде, где тела коротки, а строк много. Разложение делится на ТРИ слагаемых,
а не на два: зона + провенанс + гуттер реплики (на этом стенде ровно 2 знака). Двучленное
разложение было верно ровно до того часа, когда реплика человека тоже стала телом.

Рычаги:
* PRAXIS_FRAME_FORM = new | old, умолчание new. Отсутствие переменной означает "new"
  по той же причине, что и у прибора: `_standenv.sanitize` снимает все PRAXIS_* вне
  ENV_KEEP/ENV_PIN, и умолчание "old" означало бы, что на стенде новая форма молча не
  проверяется, а гейт при этом говорит OK. Под "old" ни `quote`, ни `inline`, ни `assay`,
  ни `Own` не исполняются ВООБЩЕ — откат обязан отдавать ВЧЕРАШНИЙ кадр, а не похожий.
* PRAXIS_FRAME_STRICT — стенд и гейт. Только здесь забытый сток и утечка строки бросают.
  В проде обе беды ТОЛЬКО считаются: кадр не имеет права не собраться, молчание вместо
  кадра хуже подделки.
"""

