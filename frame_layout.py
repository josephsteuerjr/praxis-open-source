def _assay_impl(frame: str) -> dict:
    text = str(frame or "")
    declared = frame_trace.declared()
    # ⚠ ПРИБОР ВЫКЛЮЧЕН ≠ КАДР СЛОМАН. При PRAXIS_FRAME_TRACE=off реестр пуст, и утверждение
    # (в) сделать не из чего: объявить тогда утечкой КАЖДУЮ нашу строку значило бы, что
    # выключенный наблюдатель роняет наблюдаемое. Утверждения (а) и (б) от реестра не зависят
    # и делаются всегда. Невозможность высказаться названа полем, а не замазана нулём.
    registry = bool(declared)
    # ⚠ СПРАШИВАЕМ СТОК, А НЕ ПЕРВЫЙ СИМВОЛ. Прежнее `startswith(">")` было последним
    # перечислением в этом проходе — и жило внутри самого прибора: сток выдаёт ШЕСТЬ форм
    # (`> кусок`, голый `>`, `>CR> кусок`, `>CR>`, и обе с `\` при суррогате), а проверка
    # угадывала одну по первому знаку. Строки `>поддельно`, `>>`, `>ZZ> метка` давали
    # leaked=0, хотя ни одну из них наш писатель произвести не мог. Теперь строка проходит
    # ровно тогда, когда её МОГ ВЫДАТЬ `gutter._emit`: разобрали и собрали обратно.
    # ⚠ Пустая строка утечкой не считается: подделать ею нечего, а объявлять каждую пустоту
    # значило бы завести реестр из пустот.
    leaked = ([line for line in text.split("\n")
               if line and not gutter.is_gutter_line(line) and line not in declared]
              if registry else [])
    snap = snapshot()
    return {
        "registry": 1 if registry else 0,
        "leaked_lines": len(leaked),
        "leaked_sample": leaked[0][:160] if leaked else "",
        "screen_break_at": gutter.screen_breaks(text),
        "lone_surrogate_at": gutter.lone_surrogates(text),
        "gutter_lines": int(snap.get("gutter_lines") or 0),
        "inline_slots": int(snap.get("inline_slots") or 0),
    }


def tape(messages):
    """Лента при РЕНДЕРЕ: гуттер накладывается ровно один раз и не хранится в сообщении.

    Её требование 06.08, дословно: «каждая реплика истории при сборке получает
    подписанный контейнер и gutter ровно один раз в итоговом кадре. Не хранить gutter как
    часть сообщения; применять при рендере».

    Решение по РОЛИ, как и у прибора, и по той же причине — оно положительное:

    * `assistant` — её собственные слова. Гуттер на них был бы не защитой, а подменой
      авторства: сборщик объявил бы её посторонней в её же кадре;
    * всё остальное — доставленный ЧУЖОЙ текст, и он идёт под гуттер целиком.

    ⚠ ЧТО ЭТО ЗАКРЫВАЕТ. До этой функции позиционная гарантия действовала ровно ОДИН ХОД:
    `agent.py` клал `history[-N:]` как есть, и подделка, приехавшая ходом раньше, стояла в
    колонке 0 следующие сто ролевых блоков — прибор её не видел вовсе, потому что бежал по
    `messages[-1]`. Её слова про этот выбор: «защита существует один ход, а потом тот же
    текст возвращается как структурно привилегированная история — это не граница, а
    отсрочка».

    ⚠ ЧЕГО НЕ ДЕЛАЕТ. Хранилище не трогается: `memory_life`, кольцо ходов и расписки
    держат дословный текст без единого `>`. Гуттер живёт только в том списке, который
    уезжает в модель, и снимается однозначно (`gutter.unquote`).

    Возвращает НОВЫЙ список — входной не мутируется: тот же список читают расписки.
    """
    out = []
    for message in list(messages or ()):
        if not isinstance(message, dict) or str(message.get("role") or "") == "assistant":
            out.append(message)
            continue
        content = message.get("content")
        if isinstance(content, str):
            out.append(dict(message, content=quote(content)))
        elif isinstance(content, list):
            out.append(dict(message, content=[
                dict(block, text=quote(block.get("text") or ""))
                if isinstance(block, dict) and block.get("type") == "text" else block
                for block in content
            ]))
        else:
            out.append(message)
    return out


def assay_tape(messages) -> dict:
    """Судит ВСЮ доставленную ленту, а не одно последнее сообщение.

    ⚠ ЗАЧЕМ. `assay` бежит по `messages[-1]`, а история приклеивается СЕМНАДЦАТЬЮ строками
    ниже (`agent.py`: `history[-HISTORY_TURNS:] + [{...}]`). Значит подделка, приехавшая
    ходом раньше, стоит в колонке 0 следующие сто ролевых блоков — и прибор её не видит
    вовсе. Позиционная гарантия действует на ХОД, а не на разговор, и до этой функции
    сказать об этом числом было нечем.

    Решение по РОЛИ, а не по содержимому — то есть положительно:

    * `assistant` — её собственные слова. Гостем они не являются, гуттера не требуют, и
      объявлять их утечкой значило бы назвать её саму посторонней в её же кадре;
    * всё остальное (`user`, `tool` и любая будущая роль) — доставленный ЧУЖОЙ текст:
      каждая физическая строка обязана быть продуктом нашего стока
      (:func:`gutter.is_gutter_line`) либо дословно совпадать с объявленной строкой.

    Это НЕ чинит ленту — это её мерит. Числа тут обязаны быть красными до тех пор, пока
    гуттер не начнёт накладываться при рендере на весь разговор: зелёный прибор над
    незащищённой лентой был бы хуже отсутствующего.
    """
    declared = frame_trace.declared()
    registry = bool(declared)
    guest, unprotected, leaked, sample = 0, 0, 0, ""
    for message in list(messages or ()):
        if not isinstance(message, dict):
            continue
        role = str(message.get("role") or "")
        if role == "assistant":
            continue
        guest += 1
        content = message.get("content")
        if isinstance(content, str):
            text = content
        elif isinstance(content, list):
            text = "\n".join(str(block.get("text") or "") for block in content
                             if isinstance(block, dict) and block.get("type") == "text")
        else:
            text = str(content or "")
        # ⚠ ПРИБОР ВЫКЛЮЧЕН ≠ ЛЕНТА СЛОМАНА — та же доктрина, что у `assay`. Без реестра
        # утверждение «эта строка не наша» сделать не из чего, и объявить тогда утечкой
        # КАЖДУЮ нашу же строку конверта значило бы, что выключенный наблюдатель роняет
        # наблюдаемое. Дриль поймал это на первом же прогоне вне следа.
        bad = ([line for line in text.split("\n")
                if line and not gutter.is_gutter_line(line) and line not in declared]
               if registry else [])
        if bad:
            unprotected += 1
            leaked += len(bad)
            if not sample:
                sample = bad[0][:160]
    return {
        "registry": 1 if registry else 0,
        "guest_messages": guest,
        "unprotected_messages": unprotected,
        "tape_leaked_lines": leaked,
        "tape_leaked_sample": sample,
    }


def assay(frame: str) -> dict:
    """ОДИН прибор на ГОТОВОМ документе — и на все каналы, включая ненаписанные.

    Три утверждения, ни одно из которых не называет ни одного канала по имени:

    (а) ни одного совпадения девяти экранных разрывов во всём кадре — обходы 1–3 (нагрузка
        в одну строку, `\\r` вместо `\\n`, невидимый знак перед опасным началом) закрыты
        разом и для канала, который появится завтра;
    (б) ни одного одинокого суррогата;
    (в) ⭐ ЗАЯВЛЕННОЕ ПРОТИВ НАБЛЮДЁННОГО. Каждая физическая строка либо начинается с `>`
        (гуттер — чужое), либо ДОСЛОВНО совпадает со строкой, объявленной эмиттером через
        `frame_trace.mark`/`declare`. Это и есть метр, пересаженный по смыслу: конец нашего
        ВЫЧИСЛЯЕТСЯ из объявленного, а не ищется по форме строки.

    Реестр (в) выводится ИЗ ВЫЗОВОВ, руками не пишется: рукописный реестр есть то же
    перечисление, что и снятый список опасных начал, только с другой стороны.

    ⚠ РЕАКЦИЯ РАЗНАЯ. Под PRAXIS_FRAME_STRICT (стенд, гейт) — исключение. В проде — ТОЛЬКО
    счёт: `note_embed("evidence", leaked_lines=…, gutter_lines=…, inline_slots=…)`. Кадр не
    имеет права не собраться; молчание вместо кадра хуже подделки, и наблюдатель не получает
    права убивать наблюдаемое (тот же урок, что увёл `assert_honest` из `seal`).
    """
    try:
        report = _assay_impl(frame)
    except Exception:
        return {}
    try:
        frame_trace.note_embed(
            "evidence",
            registry=report["registry"],
            leaked_lines=report["leaked_lines"],
            gutter_lines=report["gutter_lines"],
            inline_slots=report["inline_slots"],
            screen_breaks=1 if report["screen_break_at"] >= 0 else 0,
            lone_surrogates=1 if report["lone_surrogate_at"] >= 0 else 0,
        )
    except Exception:
        pass
    if strict() and (report["leaked_lines"] or report["screen_break_at"] >= 0
                     or report["lone_surrogate_at"] >= 0):
        raise FrameFormError(
            "форма кадра нарушена: необъявленных строк {leaked_lines}, экранный разрыв на "
            "{screen_break_at}, одинокий суррогат на {lone_surrogate_at}; первая утечка: "
            "{leaked_sample!r}".format(**report))
    return report
