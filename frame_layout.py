def form_new() -> bool:
    """new | old. Отсутствие переменной = new (см. докстринг модуля)."""
    raw = (os.getenv(ENV_LEVER) or "").strip().lower()
    return raw not in ("old", "0", "off", "false", "no")


def strict() -> bool:
    """Стенд и гейт. В проде False всегда: кадр не имеет права не собраться."""
    if _STRICT_OVERRIDE is not None:
        return _STRICT_OVERRIDE
    return (os.getenv(ENV_STRICT) or "").strip().lower() in ("1", "true", "yes", "on", "strict")


def set_strict(value: bool | None) -> bool | None:
    """Переключить строгость В ОБХОД окружения; возвращает ПРЕЖНИЙ override.

    Тесты обязаны ходить сюда, а не в os.environ: детектор утечек стенда краснит любую
    PRAXIS_*, оставшуюся после теста, а `_standenv.sanitize` снимает её и до теста.
    Восстановление — `addCleanup(set_strict, prev)`.
    """
    global _STRICT_OVERRIDE
    previous = _STRICT_OVERRIDE
    _STRICT_OVERRIDE = None if value is None else bool(value)
    return previous


